#include "RuleCompiler.h"

namespace Luwu::Dsl
{

class TargetBuilderA64 : public TargetBuilder
{
public:
    std::string archName() const override { return "A64"; }
    std::string loweringClass() const override { return "IrLoweringA64"; }
    std::string destRegVar() const override { return "inst.regA64"; }

    void emitPreamble(std::ostream& os) override
    {
        os << "// Auto-generated by luwu-dsl-compiler from rules.luna. DO NOT EDIT!\n";
        os << "#pragma once\n\n";
        os << "#include \"IrLoweringA64.h\"\n";
        os << "#include \"EmitCommonA64.h\"\n";
        os << "#include \"lstate.h\"\n\n";
        os << "namespace Luau\n";
        os << "{\n";
        os << "namespace CodeGen\n";
        os << "{\n";
        os << "namespace A64\n";
        os << "{\n\n";
    }

    void emitPostamble(std::ostream& os) override
    {
        os << "} // namespace A64\n";
        os << "} // namespace CodeGen\n";
        os << "} // namespace Luau\n";
    }

    void emitAllocProduce(std::ostream& os, const std::string& indent, TypeKind type, bool isReuse, const std::vector<std::string>& rawOps) override
    {
        bool is32 = (type == TypeKind::I32 || type == TypeKind::U32);
        std::string kind = is32 ? "KindA64::w" : "KindA64::x";
        if (isReuse)
        {
            os << indent << "inst.regA64 = regs.allocReuse(" << kind << ", index, {";
            for (size_t i = 0; i < rawOps.size(); ++i)
            {
                if (i > 0)
                    os << ", ";
                os << rawOps[i];
            }
            os << "});\n";
        }
        else
            os << indent << "inst.regA64 = regs.allocReg(" << kind << ", index);\n";
    }

    std::string toReg(std::ostream& os, const std::string& indent, EvalContext& ctx, const Operand& op, const std::string& destReg = "", const std::string& preferredKind = "") override
    {
        (void)destReg;
        if (op.kind == OperandKind::Reg || op.kind == OperandKind::Imm)
            return op.text;

        if (op.kind == OperandKind::Mem)
        {
            std::string tmp = ctx.nextTemp("tmp_reg");
            std::string kind = (op.type == TypeKind::U8 || op.type == TypeKind::U32 || op.type == TypeKind::I32 || op.type == TypeKind::I16)
                ? "KindA64::w"
                : (preferredKind.empty() ? "KindA64::x" : preferredKind);
            std::string ldr = (op.type == TypeKind::U8) ? "build.ldrb" : "build.ldr";

            ctx.addDecl("RegisterA64 " + tmp + " = regs.allocTemp(" + kind + ");");
            os << indent << ldr << "(" << tmp << ", mem(" << op.memBase << ", " << op.memOffset << "));\n";
            return tmp;
        }

        throw std::runtime_error("Cannot convert operand to register in A64");
    }

    std::string resolveMemBase(std::ostream& os, const std::string& indent, EvalContext& ctx, const SExpr& baseExpr, const Operand& baseOp, const std::string& destReg = "") override
    {
        (void)baseExpr;
        (void)destReg;
        return toReg(os, indent, ctx, baseOp, "", "KindA64::x");
    }

    Operand emitCodeAddress(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& offset, const std::string& destReg) override
    {
        if (destReg.empty())
        {
            std::string var = ctx.nextTemp("tmp_addr");
            ctx.addDecl("RegisterA64 " + var + " = regs.allocTemp(KindA64::x);");
            os << indent << "emitAddOffset(build, " << var << ", rCode, (" << offset << ") * sizeof(Instruction));\n";
            return Operand::makeReg(TypeKind::Ptr, var);
        }
        else
        {
            os << indent << "emitAddOffset(build, " << destReg << ", rCode, (" << offset << ") * sizeof(Instruction));\n";
            return Operand::makeReg(TypeKind::Ptr, destReg);
        }
    }

    Operand emitLoad(std::ostream& os, const std::string& indent, EvalContext& ctx, TypeKind type, const std::string& base, const std::string& offset, const std::string& destReg) override
    {
        (void)ctx;
        if (!destReg.empty())
        {
            std::string instr = (type == TypeKind::U8) ? "build.ldrb" : "build.ldr";
            os << indent << instr << "(" << destReg << ", mem(" << base << ", " << offset << "));\n";
            return Operand::makeReg(type, destReg);
        }
        return Operand::makeMem(type, base, offset);
    }

    void emitStore(std::ostream& os, const std::string& indent, EvalContext& ctx, TypeKind type, const std::string& base, const std::string& offset, const Operand& val, const std::string& valName = "") override
    {
        (void)valName;
        std::string pref = (type == TypeKind::U8) ? "KindA64::w" : "KindA64::x";
        std::string valReg;
        if (val.kind == OperandKind::Mem && !val.memBase.empty() && val.memBase != base && val.memBase.rfind("tmp_reg", 0) == 0)
        {
            std::string ldr = (val.type == TypeKind::U8) ? "build.ldrb" : "build.ldr";
            os << indent << ldr << "(" << val.memBase << ", mem(" << val.memBase << ", " << val.memOffset << "));\n";
            valReg = val.memBase;
        }
        else
        {
            valReg = toReg(os, indent, ctx, val, "", pref);
        }
        std::string instr = (type == TypeKind::U8) ? "build.strb" : "build.str";
        os << indent << instr << "(" << valReg << ", mem(" << base << ", " << offset << "));\n";
    }

    void emitBranchIfZero(std::ostream& os, const std::string& indent, EvalContext& ctx, bool notZero, const Operand& val, const std::string& labelOp) override
    {
        std::string pref = (val.type == TypeKind::Ptr) ? "KindA64::x" : "KindA64::w";
        std::string valReg = toReg(os, indent, ctx, val, "", pref);
        std::string instr = notZero ? "build.cbnz" : "build.cbz";
        ctx.addDecl("Label fresh;");
        os << indent << instr << "(" << valReg << ", lowering.getTargetLabel(" << labelOp << ", index, fresh));\n";
        os << indent << "lowering.finalizeTargetLabel(" << labelOp << ", index, fresh);\n";
    }

    void emitBranchIfEqual(std::ostream& os, const std::string& indent, EvalContext& ctx, bool notEqual, const Operand& val, const Operand& expected, const std::string& labelOp) override
    {
        std::string valReg = toReg(os, indent, ctx, val, "", "KindA64::w");
        std::string cond = notEqual ? "ConditionA64::NotEqual" : "ConditionA64::Equal";
        ctx.addDecl("Label fresh;");
        os << indent << "build.cmp(" << valReg << ", uint16_t(" << expected.text << "));\n";
        os << indent << "build.b(" << cond << ", lowering.getTargetLabel(" << labelOp << ", index, fresh));\n";
        os << indent << "lowering.finalizeTargetLabel(" << labelOp << ", index, fresh);\n";
    }

    void emitBranchIfNegative(std::ostream& os, const std::string& indent, EvalContext& ctx, const Operand& val, const std::string& labelOp) override
    {
        std::string valReg = toReg(os, indent, ctx, val, "", "KindA64::w");
        os << indent << "build.cmp(" << valReg << ", uint16_t(0));\n";
        os << indent << "build.b(ConditionA64::Less, lowering.labelOp(" << labelOp << "));\n";
    }

    Operand emitSignExtend(std::ostream& os, const std::string& indent, EvalContext& ctx, int bits, const Operand& val, const std::string& destReg) override
    {
        std::string valReg = toReg(os, indent, ctx, val, "", "KindA64::w");
        std::string target = destReg.empty() ? ctx.nextTemp("tmp_sext") : destReg;
        if (destReg.empty())
            os << indent << "RegisterA64 " << target << " = regs.allocTemp(KindA64::w);\n";
        os << indent << "build.sbfx(" << target << ", " << valReg << ", 0, " << bits << ");\n";
        return Operand::makeReg(TypeKind::I32, target);
    }

    Operand emitTruncateUint(std::ostream& os, const std::string& indent, EvalContext& ctx, const Operand& val, const std::string& destReg) override
    {
        (void)ctx;
        os << indent << "build.ubfx(castReg(KindA64::x, " << destReg << "), castReg(KindA64::x, " << val.text << "), 0, 32);\n";
        return Operand::makeReg(TypeKind::U32, destReg);
    }

    Operand emitIsEqual(std::ostream& os, const std::string& indent, EvalContext& ctx, const Operand& val, const Operand& expected, const std::string& destReg) override
    {
        std::string valReg = toReg(os, indent, ctx, val, "", "KindA64::w");
        os << indent << "build.cmp(" << valReg << ", uint16_t(" << expected.text << "));\n";
        os << indent << "build.cset(" << destReg << ", ConditionA64::Equal);\n";
        return Operand::makeReg(TypeKind::U32, destReg);
    }

    Operand emitByteSwap(std::ostream& os, const std::string& indent, EvalContext& ctx, int bits, const std::string& rawOp, const std::string& destReg) override
    {
        (void)ctx;
        std::string tempFn = (bits == 64) ? "lowering.tempInt64" : "lowering.tempUint";
        os << indent << "RegisterA64 temp = " << tempFn << "(" << rawOp << ");\n";
        os << indent << "build.rev(" << destReg << ", temp);\n";
        return Operand::makeReg(bits == 64 ? TypeKind::I64 : TypeKind::U32, destReg);
    }

    Operand emitBitwiseNot(std::ostream& os, const std::string& indent, EvalContext& ctx, int bits, const std::string& rawOp, const std::string& destReg) override
    {
        (void)ctx;
        std::string tempFn = (bits == 64) ? "lowering.tempInt64" : "lowering.tempUint";
        os << indent << "RegisterA64 temp = " << tempFn << "(" << rawOp << ");\n";
        os << indent << "build.mvn_(" << destReg << ", temp);\n";
        return Operand::makeReg(bits == 64 ? TypeKind::I64 : TypeKind::U32, destReg);
    }

    Operand emitBitwiseBinOp(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& op, int bits, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        (void)ctx;
        std::string a64Op = (op == "and") ? "and_" : ((op == "or") ? "orr" : "eor");
        if (bits == 32)
        {
            os << indent << "if (" << rawOpA << ".kind == IrOpKind::Inst && " << rawOpB << ".kind == IrOpKind::Constant &&\n";
            os << indent << "    AssemblyBuilderA64::isMaskSupported(unsigned(lowering.intOp(" << rawOpB << "))))\n";
            os << indent << "    build." << a64Op << "(" << destReg << ", lowering.regOp(" << rawOpA << "), unsigned(lowering.intOp(" << rawOpB << ")));\n";
            os << indent << "else\n";
            os << indent << "{\n";
            os << indent << "    RegisterA64 temp1 = lowering.tempUint(" << rawOpA << ");\n";
            os << indent << "    RegisterA64 temp2 = lowering.tempUint(" << rawOpB << ");\n";
            os << indent << "    build." << a64Op << "(" << destReg << ", temp1, temp2);\n";
            os << indent << "}\n";
        }
        else
        {
            os << indent << "RegisterA64 temp1 = lowering.tempInt64(" << rawOpA << ");\n";
            os << indent << "RegisterA64 temp2 = lowering.tempInt64(" << rawOpB << ");\n";
            os << indent << "build." << a64Op << "(" << destReg << ", temp1, temp2);\n";
        }
        return Operand::makeReg(bits == 64 ? TypeKind::I64 : TypeKind::U32, destReg);
    }

    Operand emitMul(std::ostream& os, const std::string& indent, EvalContext& ctx, int bits, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        (void)ctx;
        (void)bits;
        os << indent << "RegisterA64 temp1 = lowering.tempInt64(" << rawOpA << ");\n";
        os << indent << "RegisterA64 temp2 = lowering.tempInt64(" << rawOpB << ");\n";
        os << indent << "build.mul(" << destReg << ", temp1, temp2);\n";
        return Operand::makeReg(TypeKind::I64, destReg);
    }

    Operand emitAddInt(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        throw std::runtime_error("emitAddInt should not be called with fine-grained rules");
    }

    Operand emitSubInt(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        throw std::runtime_error("emitSubInt should not be called with fine-grained rules");
    }

    Operand emitAddInt64(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        throw std::runtime_error("emitAddInt64 should not be called with fine-grained rules");
    }

    Operand emitSubInt64(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        throw std::runtime_error("emitSubInt64 should not be called with fine-grained rules");
    }

    void emitAddImm(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg, int bits) override
    {
        (void)ctx;
        if (bits == 64)
            os << indent << "build.add(" << destReg << ", lowering.tempInt64(" << rawOpA << "), uint16_t(lowering.int64Op(" << rawOpB << ")));\n";
        else
            os << indent << "build.add(" << destReg << ", lowering.regOp(" << rawOpA << "), uint16_t(lowering.intOp(" << rawOpB << ")));\n";
    }

    void emitAddReg(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg, int bits) override
    {
        (void)ctx;
        if (bits == 64)
        {
            os << indent << "RegisterA64 temp1 = lowering.tempInt64(" << rawOpA << ");\n";
            os << indent << "RegisterA64 temp2 = lowering.tempInt64(" << rawOpB << ");\n";
            os << indent << "build.add(" << destReg << ", temp1, temp2);\n";
        }
        else
        {
            os << indent << "RegisterA64 temp1 = lowering.tempInt(" << rawOpA << ");\n";
            os << indent << "RegisterA64 temp2 = lowering.tempInt(" << rawOpB << ");\n";
            os << indent << "build.add(" << destReg << ", temp1, temp2);\n";
        }
    }

    void emitSubImm(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg, int bits) override
    {
        (void)ctx;
        if (bits == 64)
            os << indent << "build.sub(" << destReg << ", lowering.tempInt64(" << rawOpA << "), uint16_t(lowering.int64Op(" << rawOpB << ")));\n";
        else
            os << indent << "build.sub(" << destReg << ", lowering.regOp(" << rawOpA << "), uint16_t(lowering.intOp(" << rawOpB << ")));\n";
    }

    void emitSubReg(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg, int bits) override
    {
        (void)ctx;
        if (bits == 64)
        {
            os << indent << "RegisterA64 temp1 = lowering.tempInt64(" << rawOpA << ");\n";
            os << indent << "RegisterA64 temp2 = lowering.tempInt64(" << rawOpB << ");\n";
            os << indent << "build.sub(" << destReg << ", temp1, temp2);\n";
        }
        else
        {
            os << indent << "RegisterA64 temp1 = lowering.tempInt(" << rawOpA << ");\n";
            os << indent << "RegisterA64 temp2 = lowering.tempInt(" << rawOpB << ");\n";
            os << indent << "build.sub(" << destReg << ", temp1, temp2);\n";
        }
    }
};

void emitA64(std::ostream& os, const std::vector<Rule>& rules)
{
    TargetBuilderA64 target;
    compileRules(os, target, rules);
}

} // namespace Luwu::Dsl
