#include "RuleCompiler.h"

namespace Luwu::Dsl
{

class TargetBuilderX64 : public TargetBuilder
{
public:
    std::string archName() const override { return "X64"; }
    std::string loweringClass() const override { return "IrLoweringX64"; }
    std::string destRegVar() const override { return "inst.regX64"; }

    void emitPreamble(std::ostream& os) override
    {
        os << "// Auto-generated by luwu-dsl-compiler from rules.luna. DO NOT EDIT!\n";
        os << "#pragma once\n\n";
        os << "#include \"IrLoweringX64.h\"\n";
        os << "#include \"EmitCommonX64.h\"\n";
        os << "#include \"EmitInstructionX64.h\"\n";
        os << "#include \"lstate.h\"\n\n";
        os << "namespace Luau\n";
        os << "{\n";
        os << "namespace CodeGen\n";
        os << "{\n";
        os << "namespace X64\n";
        os << "{\n\n";
    }

    void emitPostamble(std::ostream& os) override
    {
        os << "} // namespace X64\n";
        os << "} // namespace CodeGen\n";
        os << "} // namespace Luau\n";
    }

    void emitAllocProduce(std::ostream& os, const std::string& indent, TypeKind type, bool isReuse, const std::vector<std::string>& rawOps) override
    {
        bool is32 = (type == TypeKind::I32 || type == TypeKind::U32);
        std::string size = is32 ? "SizeX64::dword" : "SizeX64::qword";
        if (isReuse)
        {
            // For integer/pointer 2-address instructions in x64, reuse is limited to the first operand (OP_A)
            std::string opToReuse = rawOps.empty() ? "" : rawOps[0];
            os << indent << "inst.regX64 = regs.allocRegOrReuse(" << size << ", index, {" << opToReuse << "});\n";
        }
        else
            os << indent << "inst.regX64 = regs.allocReg(" << size << ", index);\n";
    }

    std::string toReg(std::ostream& os, const std::string& indent, EvalContext& ctx, const Operand& op, const std::string& destReg = "", const std::string& preferredKind = "") override
    {
        (void)preferredKind;
        if (op.kind == OperandKind::Reg || op.kind == OperandKind::Imm)
            return op.text;

        if (op.text == "rClosure")
        {
            if (!destReg.empty())
            {
                os << indent << "build.mov(" << destReg << ", sClosure);\n";
                return destReg;
            }
            std::string tmp = ctx.nextTemp("tmp_cl");
            os << indent << "ScopedRegX64 " << tmp << "{regs, SizeX64::qword};\n";
            os << indent << "build.mov(" << tmp << ".reg, sClosure);\n";
            return tmp + ".reg";
        }

        if (op.kind == OperandKind::Mem)
        {
            if (!destReg.empty())
            {
                std::string sizeStr = (op.type == TypeKind::U8) ? "byte" : ((op.type == TypeKind::U32 || op.type == TypeKind::I32) ? "dword" : "qword");
                if (op.type == TypeKind::U8)
                    os << indent << "build.movzx(" << destReg << ", byte[" << op.memBase << " + " << op.memOffset << "]);\n";
                else
                    os << indent << "build.mov(" << destReg << ", " << sizeStr << "[" << op.memBase << " + " << op.memOffset << "]);\n";
                return destReg;
            }

            std::string tmp = ctx.nextTemp("tmp_mem");
            std::string sizeStr = (op.type == TypeKind::U8) ? "byte" : ((op.type == TypeKind::U32 || op.type == TypeKind::I32) ? "dword" : "qword");
            ctx.addDecl("ScopedRegX64 " + tmp + "{regs, SizeX64::qword};");
            os << indent << "build.mov(" << tmp << ".reg, " << sizeStr << "[" << op.memBase << " + " << op.memOffset << "]);\n";
            return tmp + ".reg";
        }

        throw std::runtime_error("Cannot convert operand to register in X64");
    }

    std::string resolveMemBase(std::ostream& os, const std::string& indent, EvalContext& ctx, const SExpr& baseExpr, const Operand& baseOp, const std::string& destReg = "") override
    {
        (void)destReg;
        if (baseExpr.isSymbol() && baseExpr.text == "rClosure")
            return "rClosure";
        if (baseOp.text == "rClosure")
            return "rClosure";

        if (baseOp.kind == OperandKind::Mem)
        {
            std::string regVar = baseExpr.isSymbol() ? toCppIdent(baseExpr.text) : ctx.nextTemp("mem");
            ctx.addDecl("ScopedRegX64 " + regVar + "{regs, SizeX64::qword};");
            os << indent << "build.mov(" << regVar << ".reg, qword[" << baseOp.memBase << " + " << baseOp.memOffset << "]);\n";
            if (baseExpr.isSymbol())
                ctx.env[baseExpr.text] = Operand::makeReg(TypeKind::Ptr, regVar + ".reg");
            return regVar + ".reg";
        }

        return baseOp.text;
    }

    Operand emitCodeAddress(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& offset, const std::string& destReg) override
    {
        if (destReg.empty())
        {
            std::string var = ctx.nextTemp("tmp_addr");
            ctx.addDecl("ScopedRegX64 " + var + "{regs, SizeX64::qword};");
            os << indent << "build.mov(" << var << ".reg, sCode);\n";
            os << indent << "build.add(" << var << ".reg, (" << offset << ") * sizeof(Instruction));\n";
            return Operand::makeReg(TypeKind::Ptr, var + ".reg");
        }
        else
        {
            os << indent << "build.mov(" << destReg << ", sCode);\n";
            os << indent << "build.add(" << destReg << ", (" << offset << ") * sizeof(Instruction));\n";
            return Operand::makeReg(TypeKind::Ptr, destReg);
        }
    }

    Operand emitLoad(std::ostream& os, const std::string& indent, EvalContext& ctx, TypeKind type, const std::string& base, const std::string& offset, const std::string& destReg) override
    {
        if (base == "rClosure")
        {
            if (!destReg.empty())
            {
                os << indent << "build.mov(" << destReg << ", sClosure);\n";
                os << indent << "build.mov(" << destReg << ", qword[" << destReg << " + " << offset << "]);\n";
                return Operand::makeReg(TypeKind::Ptr, destReg);
            }
            else
            {
                std::string var = ctx.nextTemp("tmp_cl");
                ctx.addDecl("ScopedRegX64 " + var + "{regs, SizeX64::qword};");
                os << indent << "build.mov(" << var << ".reg, sClosure);\n";
                os << indent << "build.mov(" << var << ".reg, qword[" << var << ".reg + " << offset << "]);\n";
                return Operand::makeReg(TypeKind::Ptr, var + ".reg");
            }
        }

        if (!destReg.empty())
        {
            if (type == TypeKind::U8)
                os << indent << "build.movzx(" << destReg << ", byte[" << base << " + " << offset << "]);\n";
            else if (type == TypeKind::U32)
                os << indent << "build.mov(" << destReg << ", dword[" << base << " + " << offset << "]);\n";
            else
                os << indent << "build.mov(" << destReg << ", qword[" << base << " + " << offset << "]);\n";
            return Operand::makeReg(type, destReg);
        }

        return Operand::makeMem(type, base, offset);
    }

    void emitStore(std::ostream& os, const std::string& indent, EvalContext& ctx, TypeKind type, const std::string& base, const std::string& offset, const Operand& val, const std::string& valName = "") override
    {
        std::string valStr;
        if (val.kind == OperandKind::Mem)
        {
            std::string memSize = (type == TypeKind::U8) ? "byte" : "qword";
            if (!val.memBase.empty() && val.memBase != base && val.memBase.find(".reg") != std::string::npos)
            {
                os << indent << "build.mov(" << val.memBase << ", " << memSize << "[" << val.memBase << " + " << val.memOffset << "]);\n";
                valStr = val.memBase;
            }
            else
            {
                std::string tempVar = !valName.empty() ? ("tmp_" + toCppIdent(valName)) : ctx.nextTemp("tmp_store");
                std::string sizeStr = (type == TypeKind::U8) ? "dword" : "qword";
                ctx.addDecl("ScopedRegX64 " + tempVar + "{regs, SizeX64::" + sizeStr + "};");
                os << indent << "build.mov(" << tempVar << ".reg, " << memSize << "[" << val.memBase << " + " << val.memOffset << "]);\n";
                valStr = tempVar + ".reg";
            }
        }
        else
        {
            valStr = val.text;
        }

        std::string ptrSize = (type == TypeKind::U8) ? "byte" : "qword";
        os << indent << "build.mov(" << ptrSize << "[" << base << " + " << offset << "], " << valStr << ");\n";
    }

    void emitBranchIfZero(std::ostream& os, const std::string& indent, EvalContext& ctx, bool notZero, const Operand& val, const std::string& labelOp) override
    {
        (void)ctx;
        if (val.kind == OperandKind::Mem)
        {
            std::string sizeStr = (val.type == TypeKind::U8) ? "byte" : ((val.type == TypeKind::U32) ? "dword" : "qword");
            os << indent << "build.cmp(" << sizeStr << "[" << val.memBase << " + " << val.memOffset << "], 0);\n";
        }
        else
        {
            os << indent << "build.cmp(" << val.text << ", 0);\n";
        }
        std::string cond = notZero ? "ConditionX64::NotEqual" : "ConditionX64::Equal";
        os << indent << "lowering.jumpOrAbortOnUndef(" << cond << ", " << labelOp << ", index, next);\n";
    }

    void emitBranchIfEqual(std::ostream& os, const std::string& indent, EvalContext& ctx, bool notEqual, const Operand& val, const Operand& expected, const std::string& labelOp) override
    {
        (void)ctx;
        std::string valStr;
        if (val.kind == OperandKind::Mem)
        {
            std::string sizeStr = (val.type == TypeKind::U8) ? "byte" : ((val.type == TypeKind::U32) ? "dword" : "qword");
            valStr = sizeStr + "[" + val.memBase + " + " + val.memOffset + "]";
        }
        else
        {
            valStr = val.text;
        }

        os << indent << "build.cmp(" << valStr << ", " << expected.text << ");\n";
        std::string cond = notEqual ? "ConditionX64::NotEqual" : "ConditionX64::Equal";
        os << indent << "lowering.jumpOrAbortOnUndef(" << cond << ", " << labelOp << ", index, next);\n";
    }

    void emitBranchIfNegative(std::ostream& os, const std::string& indent, EvalContext& ctx, const Operand& val, const std::string& labelOp) override
    {
        std::string valStr = toReg(os, indent, ctx, val);
        os << indent << "build.test(" << valStr << ", " << valStr << ");\n";
        os << indent << "build.jcc(ConditionX64::Less, lowering.labelOp(" << labelOp << "));\n";
    }

    Operand emitSignExtend(std::ostream& os, const std::string& indent, EvalContext& ctx, int bits, const Operand& val, const std::string& destReg) override
    {
        std::string valReg = toReg(os, indent, ctx, val);
        std::string target = destReg.empty() ? ctx.nextTemp("tmp_sext") : destReg;
        if (destReg.empty())
            os << indent << "ScopedRegX64 " << target << "{regs, SizeX64::dword};\n";
        std::string d = destReg.empty() ? (target + ".reg") : target;
        std::string subReg = (bits == 8) ? ("byteReg(" + valReg + ")") : ("wordReg(" + valReg + ")");
        os << indent << "build.movsx(" << d << ", " << subReg << ");\n";
        return Operand::makeReg(TypeKind::I32, d);
    }

    Operand emitTruncateUint(std::ostream& os, const std::string& indent, EvalContext& ctx, const Operand& val, const std::string& destReg) override
    {
        (void)ctx;
        os << indent << "build.mov(" << destReg << ", " << val.text << ");\n";
        return Operand::makeReg(TypeKind::U32, destReg);
    }

    Operand emitIsEqual(std::ostream& os, const std::string& indent, EvalContext& ctx, const Operand& val, const Operand& expected, const std::string& destReg) override
    {
        (void)ctx;
        os << indent << "build.xor_(" << destReg << ", " << destReg << ");\n";
        if (val.kind == OperandKind::Mem)
        {
            std::string sizeStr = (val.type == TypeKind::U8) ? "byte" : ((val.type == TypeKind::U32 || val.type == TypeKind::I32) ? "dword" : "qword");
            os << indent << "build.cmp(" << sizeStr << "[" << val.memBase << " + " << val.memOffset << "], " << expected.text << ");\n";
        }
        else
        {
            os << indent << "build.cmp(" << val.text << ", " << expected.text << ");\n";
        }
        os << indent << "build.setcc(ConditionX64::Equal, byteReg(" << destReg << "));\n";
        return Operand::makeReg(TypeKind::U32, destReg);
    }

    Operand emitByteSwap(std::ostream& os, const std::string& indent, EvalContext& ctx, int bits, const std::string& rawOp, const std::string& destReg) override
    {
        (void)ctx;
        std::string memRegFn = (bits == 64) ? "lowering.memRegInt64Op" : "lowering.memRegUintOp";
        os << indent << "if (" << rawOp << ".kind != IrOpKind::Inst || " << destReg << " != lowering.regOp(" << rawOp << "))\n";
        os << indent << "    build.mov(" << destReg << ", " << memRegFn << "(" << rawOp << "));\n\n";
        os << indent << "build.bswap(" << destReg << ");\n";
        return Operand::makeReg(bits == 64 ? TypeKind::I64 : TypeKind::U32, destReg);
    }

    Operand emitBitwiseNot(std::ostream& os, const std::string& indent, EvalContext& ctx, int bits, const std::string& rawOp, const std::string& destReg) override
    {
        (void)ctx;
        std::string memRegFn = (bits == 64) ? "lowering.memRegInt64Op" : "lowering.memRegUintOp";
        os << indent << "if (" << rawOp << ".kind != IrOpKind::Inst || " << destReg << " != lowering.regOp(" << rawOp << "))\n";
        os << indent << "    build.mov(" << destReg << ", " << memRegFn << "(" << rawOp << "));\n\n";
        os << indent << "build.not_(" << destReg << ");\n";
        return Operand::makeReg(bits == 64 ? TypeKind::I64 : TypeKind::U32, destReg);
    }

    Operand emitBitwiseBinOp(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& op, int bits, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        (void)ctx;
        std::string x64Op = (op == "and") ? "and_" : ((op == "or") ? "or_" : "xor_");
        std::string memRegFn = (bits == 64) ? "lowering.memRegInt64Op" : "lowering.memRegUintOp";
        os << indent << "if (" << rawOpA << ".kind != IrOpKind::Inst || " << destReg << " != lowering.regOp(" << rawOpA << "))\n";
        os << indent << "    build.mov(" << destReg << ", " << memRegFn << "(" << rawOpA << "));\n\n";
        os << indent << "build." << x64Op << "(" << destReg << ", " << memRegFn << "(" << rawOpB << "));\n";
        return Operand::makeReg(bits == 64 ? TypeKind::I64 : TypeKind::U32, destReg);
    }

    Operand emitMul(std::ostream& os, const std::string& indent, EvalContext& ctx, int bits, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        (void)ctx;
        (void)bits;
        os << indent << "build.mov(" << destReg << ", lowering.memRegInt64Op(" << rawOpA << "));\n";
        os << indent << "build.imul(" << destReg << ", lowering.memRegInt64Op(" << rawOpB << "));\n";
        return Operand::makeReg(TypeKind::I64, destReg);
    }

    Operand emitAddInt(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        throw std::runtime_error("emitAddInt should not be called with fine-grained rules");
    }

    Operand emitSubInt(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        throw std::runtime_error("emitSubInt should not be called with fine-grained rules");
    }

    Operand emitAddInt64(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        throw std::runtime_error("emitAddInt64 should not be called with fine-grained rules");
    }

    Operand emitSubInt64(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        throw std::runtime_error("emitSubInt64 should not be called with fine-grained rules");
    }

    void emitLeaReg(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpBase, const std::string& rawOpOffset, const std::string& destReg, int bits) override
    {
        (void)ctx;
        (void)bits;
        os << indent << "build.lea(" << destReg << ", addr[lowering.regOp(" << rawOpBase << ") + lowering.regOp(" << rawOpOffset << ")]);\n";
    }

    void emitLeaImm(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpBase, const std::string& rawOpOffset, const std::string& destReg, int bits) override
    {
        (void)ctx;
        if (bits == 64)
            os << indent << "build.lea(" << destReg << ", addr[lowering.regOp(" << rawOpBase << ") + int32_t(lowering.int64Op(" << rawOpOffset << "))]);\n";
        else
            os << indent << "build.lea(" << destReg << ", addr[lowering.regOp(" << rawOpBase << ") + lowering.intOp(" << rawOpOffset << ")]);\n";
    }

    void emitLeaSub(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOpBase, const std::string& rawOpOffset, const std::string& destReg, int bits) override
    {
        (void)ctx;
        if (bits == 64)
            os << indent << "build.lea(" << destReg << ", addr[lowering.regOp(" << rawOpBase << ") - int32_t(lowering.int64Op(" << rawOpOffset << "))]);\n";
        else
            os << indent << "build.lea(" << destReg << ", addr[lowering.regOp(" << rawOpBase << ") - lowering.intOp(" << rawOpOffset << ")]);\n";
    }

    void emitAddOp(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOp, const std::string& destReg, int bits) override
    {
        (void)ctx;
        (void)bits;
        os << indent << "build.add(" << destReg << ", lowering.regOp(" << rawOp << "));\n";
    }

    void emitAddImmOp(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOp, const std::string& destReg, int bits) override
    {
        (void)ctx;
        if (bits == 64)
            os << indent << "build.add(" << destReg << ", int32_t(lowering.int64Op(" << rawOp << ")));\n";
        else
            os << indent << "build.add(" << destReg << ", lowering.intOp(" << rawOp << "));\n";
    }

    void emitSubOp(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOp, const std::string& destReg, int bits) override
    {
        (void)ctx;
        (void)bits;
        os << indent << "build.sub(" << destReg << ", lowering.regOp(" << rawOp << "));\n";
    }

    void emitSubImmOp(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOp, const std::string& destReg, int bits) override
    {
        (void)ctx;
        if (bits == 64)
            os << indent << "build.sub(" << destReg << ", int32_t(lowering.int64Op(" << rawOp << ")));\n";
        else
            os << indent << "build.sub(" << destReg << ", lowering.intOp(" << rawOp << "));\n";
    }

    void emitInc(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& destReg) override
    {
        (void)ctx;
        os << indent << "build.inc(" << destReg << ");\n";
    }

    void emitMovReg(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOp, const std::string& destReg) override
    {
        (void)ctx;
        os << indent << "build.mov(" << destReg << ", lowering.regOp(" << rawOp << "));\n";
    }

    void emitMovImm(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOp, const std::string& destReg, int bits) override
    {
        (void)ctx;
        if (bits == 64)
            os << indent << "build.mov64(" << destReg << ", lowering.int64Op(" << rawOp << "));\n";
        else
            os << indent << "build.mov(" << destReg << ", lowering.intOp(" << rawOp << "));\n";
    }

    void emitAddTmp64(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOp, const std::string& destReg) override
    {
        (void)ctx;
        os << indent << "ScopedRegX64 tmp{regs, SizeX64::qword};\n";
        os << indent << "build.mov64(tmp.reg, lowering.int64Op(" << rawOp << "));\n";
        os << indent << "build.add(" << destReg << ", tmp.reg);\n";
    }

    void emitSubTmp64(std::ostream& os, const std::string& indent, EvalContext& ctx, const std::string& rawOp, const std::string& destReg) override
    {
        (void)ctx;
        os << indent << "ScopedRegX64 tmp{regs, SizeX64::qword};\n";
        os << indent << "build.mov64(tmp.reg, lowering.int64Op(" << rawOp << "));\n";
        os << indent << "build.sub(" << destReg << ", tmp.reg);\n";
    }
};

void emitX64(std::ostream& os, const std::vector<Rule>& rules)
{
    TargetBuilderX64 target;
    compileRules(os, target, rules);
}

} // namespace Luwu::Dsl
