#include "RuleCompiler.h"

namespace Luwu::Dsl
{

class TargetBuilderX64 : public TargetBuilder
{
public:
    std::string archName() const override { return "X64"; }
    std::string loweringClass() const override { return "IrLoweringX64"; }
    std::string destRegVar() const override { return "inst.regX64"; }

    void emitPreamble(CodeWriter& out) override
    {
        out.raw("// Auto-generated by luwu-dsl-compiler from rules.luna. DO NOT EDIT!\n"
                "#pragma once\n\n"
                "#include \"IrLoweringX64.h\"\n"
                "#include \"EmitCommonX64.h\"\n"
                "#include \"EmitInstructionX64.h\"\n"
                "#include \"lstate.h\"\n\n"
                "namespace Luau\n"
                "{\n"
                "namespace CodeGen\n"
                "{\n"
                "namespace X64\n"
                "{\n\n");
    }

    void emitPostamble(CodeWriter& out) override
    {
        out.raw("} // namespace X64\n"
                "} // namespace CodeGen\n"
                "} // namespace Luau\n");
    }

    void emitAllocProduce(CodeWriter& out, TypeKind type, bool isReuse, const std::vector<std::string>& rawOps) override
    {
        bool is32 = (type == TypeKind::I32 || type == TypeKind::U32);
        std::string sizeStr = is32 ? "SizeX64::dword" : "SizeX64::qword";
        if (isReuse)
        {
            out.line("inst.regX64 = regs.allocRegOrReuse(" + sizeStr + ", index, {" + rawOps[0] + "});");
        }
        else
            out.line("inst.regX64 = regs.allocReg(" + sizeStr + ", index);");
    }

    std::string toReg(CodeWriter& out, EvalContext& ctx, const Operand& op, const std::string& destReg = "", const std::string& preferredKind = "") override
    {
        (void)preferredKind;
        if (op.kind == OperandKind::Reg || op.kind == OperandKind::Imm)
            return op.text;

        if (op.kind == OperandKind::Mem)
        {
            std::string sizeStr = (op.type == TypeKind::U8) ? "byte" : ((op.type == TypeKind::U32) ? "dword" : "qword");
            if (destReg.empty())
            {
                std::string tmp = ctx.nextTemp("tmp_reg");
                std::string regSize = (op.type == TypeKind::U8) ? "dword" : sizeStr;
                ctx.addDecl("ScopedRegX64 " + tmp + "{regs, SizeX64::" + regSize + "};");
                out.line("build.mov(" + tmp + ".reg, " + sizeStr + "[" + op.memBase + " + " + op.memOffset + "]);");
                return tmp + ".reg";
            }
            else
            {
                out.line("build.mov(" + destReg + ", " + sizeStr + "[" + op.memBase + " + " + op.memOffset + "]);");
                return destReg;
            }
        }

        throw CompileError(SourceLocation{}, "Cannot convert operand to register in X64");
    }

    std::string resolveMemBase(CodeWriter& out, EvalContext& ctx, const SExpr& baseExpr, const Operand& baseOp, const std::string& destReg = "") override
    {
        (void)destReg;
        if (baseExpr.isSymbol() && baseExpr.text == "rClosure")
            return "rClosure";
        if (baseOp.text == "rClosure")
            return "rClosure";

        if (baseOp.kind == OperandKind::Mem)
        {
            std::string regVar = baseExpr.isSymbol() ? toCppIdent(baseExpr.text) : ctx.nextTemp("mem");
            ctx.addDecl("ScopedRegX64 " + regVar + "{regs, SizeX64::qword};");
            out.line("build.mov(" + regVar + ".reg, qword[" + baseOp.memBase + " + " + baseOp.memOffset + "]);");
            if (baseExpr.isSymbol())
                ctx.updateOrBind(baseExpr.text, Operand::makeReg(TypeKind::Ptr, regVar + ".reg"));
            return regVar + ".reg";
        }

        return baseOp.text;
    }

    Operand emitCodeAddress(CodeWriter& out, EvalContext& ctx, const std::string& offset, const std::string& destReg) override
    {
        if (destReg.empty())
        {
            std::string var = ctx.nextTemp("tmp_addr");
            ctx.addDecl("ScopedRegX64 " + var + "{regs, SizeX64::qword};");
            out.line("build.mov(" + var + ".reg, sCode);");
            out.line("build.add(" + var + ".reg, (" + offset + ") * sizeof(Instruction));");
            return Operand::makeReg(TypeKind::Ptr, var + ".reg");
        }
        else
        {
            out.line("build.mov(" + destReg + ", sCode);");
            out.line("build.add(" + destReg + ", (" + offset + ") * sizeof(Instruction));");
            return Operand::makeReg(TypeKind::Ptr, destReg);
        }
    }

    Operand emitLoad(CodeWriter& out, EvalContext& ctx, TypeKind type, const std::string& base, const std::string& offset, const std::string& destReg) override
    {
        if (base == "rClosure")
        {
            if (!destReg.empty())
            {
                out.line("build.mov(" + destReg + ", sClosure);");
                out.line("build.mov(" + destReg + ", qword[" + destReg + " + " + offset + "]);");
                return Operand::makeReg(TypeKind::Ptr, destReg);
            }
            else
            {
                std::string var = ctx.nextTemp("tmp_cl");
                ctx.addDecl("ScopedRegX64 " + var + "{regs, SizeX64::qword};");
                out.line("build.mov(" + var + ".reg, sClosure);");
                out.line("build.mov(" + var + ".reg, qword[" + var + ".reg + " + offset + "]);");
                return Operand::makeReg(TypeKind::Ptr, var + ".reg");
            }
        }

        if (!destReg.empty())
        {
            if (type == TypeKind::U8)
                out.line("build.movzx(" + destReg + ", byte[" + base + " + " + offset + "]);");
            else if (type == TypeKind::U32)
                out.line("build.mov(" + destReg + ", dword[" + base + " + " + offset + "]);");
            else
                out.line("build.mov(" + destReg + ", qword[" + base + " + " + offset + "]);");
            return Operand::makeReg(type, destReg);
        }

        return Operand::makeMem(type, base, offset);
    }

    void emitStore(CodeWriter& out, EvalContext& ctx, TypeKind type, const std::string& base, const std::string& offset, const Operand& val, const std::string& valName = "") override
    {
        std::string valStr;
        if (val.kind == OperandKind::Mem)
        {
            std::string memSize = (type == TypeKind::U8) ? "byte" : "qword";
            if (!val.memBase.empty() && val.memBase != base && val.memBase.find(".reg") != std::string::npos)
            {
                out.line("build.mov(" + val.memBase + ", " + memSize + "[" + val.memBase + " + " + val.memOffset + "]);");
                valStr = val.memBase;
            }
            else
            {
                std::string tempVar = !valName.empty() ? ("tmp_" + toCppIdent(valName)) : ctx.nextTemp("tmp_store");
                std::string sizeStr = (type == TypeKind::U8) ? "dword" : "qword";
                ctx.addDecl("ScopedRegX64 " + tempVar + "{regs, SizeX64::" + sizeStr + "};");
                out.line("build.mov(" + tempVar + ".reg, " + memSize + "[" + val.memBase + " + " + val.memOffset + "]);");
                valStr = tempVar + ".reg";
            }
        }
        else
        {
            valStr = val.text;
        }

        std::string ptrSize = (type == TypeKind::U8) ? "byte" : "qword";
        out.line("build.mov(" + ptrSize + "[" + base + " + " + offset + "], " + valStr + ");");
    }

    void emitBranchIfZero(CodeWriter& out, EvalContext& ctx, bool notZero, const Operand& val, const std::string& labelOp) override
    {
        (void)ctx;
        if (val.kind == OperandKind::Mem)
        {
            std::string sizeStr = (val.type == TypeKind::U8) ? "byte" : ((val.type == TypeKind::U32) ? "dword" : "qword");
            out.line("build.cmp(" + sizeStr + "[" + val.memBase + " + " + val.memOffset + "], 0);");
        }
        else
        {
            out.line("build.cmp(" + val.text + ", 0);");
        }
        std::string cond = notZero ? "ConditionX64::NotEqual" : "ConditionX64::Equal";
        out.line("lowering.jumpOrAbortOnUndef(" + cond + ", " + labelOp + ", index, next);");
    }

    void emitBranchIfEqual(CodeWriter& out, EvalContext& ctx, bool notEqual, const Operand& val, const Operand& expected, const std::string& labelOp) override
    {
        (void)ctx;
        std::string valStr;
        if (val.kind == OperandKind::Mem)
        {
            std::string sizeStr = (val.type == TypeKind::U8) ? "byte" : ((val.type == TypeKind::U32) ? "dword" : "qword");
            valStr = sizeStr + "[" + val.memBase + " + " + val.memOffset + "]";
        }
        else
        {
            valStr = val.text;
        }

        out.line("build.cmp(" + valStr + ", " + expected.text + ");");
        std::string cond = notEqual ? "ConditionX64::NotEqual" : "ConditionX64::Equal";
        out.line("lowering.jumpOrAbortOnUndef(" + cond + ", " + labelOp + ", index, next);");
    }

    void emitBranchIfNegative(CodeWriter& out, EvalContext& ctx, const Operand& val, const std::string& labelOp) override
    {
        std::string valStr = toReg(out, ctx, val);
        out.line("build.test(" + valStr + ", " + valStr + ");");
        out.line("build.jcc(ConditionX64::Less, lowering.labelOp(" + labelOp + "));");
    }

    Operand emitSignExtend(CodeWriter& out, EvalContext& ctx, int bits, const Operand& val, const std::string& destReg) override
    {
        std::string valReg = toReg(out, ctx, val);
        std::string target = destReg.empty() ? ctx.nextTemp("tmp_sext") : destReg;
        if (destReg.empty())
            out.line("ScopedRegX64 " + target + "{regs, SizeX64::dword};");
        std::string d = destReg.empty() ? (target + ".reg") : target;
        std::string subReg = (bits == 8) ? ("byteReg(" + valReg + ")") : ("wordReg(" + valReg + ")");
        out.line("build.movsx(" + d + ", " + subReg + ");");
        return Operand::makeReg(TypeKind::I32, d);
    }

    Operand emitTruncateUint(CodeWriter& out, EvalContext& ctx, const Operand& val, const std::string& destReg) override
    {
        (void)ctx;
        out.line("build.mov(" + destReg + ", " + val.text + ");");
        return Operand::makeReg(TypeKind::U32, destReg);
    }

    Operand emitIsEqual(CodeWriter& out, EvalContext& ctx, const Operand& val, const Operand& expected, const std::string& destReg) override
    {
        (void)ctx;
        out.line("build.xor_(" + destReg + ", " + destReg + ");");
        if (val.kind == OperandKind::Mem)
        {
            std::string sizeStr = (val.type == TypeKind::U8) ? "byte" : ((val.type == TypeKind::U32 || val.type == TypeKind::I32) ? "dword" : "qword");
            out.line("build.cmp(" + sizeStr + "[" + val.memBase + " + " + val.memOffset + "], " + expected.text + ");");
        }
        else
        {
            out.line("build.cmp(" + val.text + ", " + expected.text + ");");
        }
        out.line("build.setcc(ConditionX64::Equal, byteReg(" + destReg + "));");
        return Operand::makeReg(TypeKind::U32, destReg);
    }

    Operand emitByteSwap(CodeWriter& out, EvalContext& ctx, int bits, const std::string& rawOp, const std::string& destReg) override
    {
        (void)ctx;
        std::string memRegFn = (bits == 64) ? "lowering.memRegInt64Op" : "lowering.memRegUintOp";
        out.line("if (" + rawOp + ".kind != IrOpKind::Inst || " + destReg + " != lowering.regOp(" + rawOp + "))");
        out.line("    build.mov(" + destReg + ", " + memRegFn + "(" + rawOp + "));");
        out.line();
        out.line("build.bswap(" + destReg + ");");
        return Operand::makeReg(bits == 64 ? TypeKind::I64 : TypeKind::U32, destReg);
    }

    Operand emitBitwiseNot(CodeWriter& out, EvalContext& ctx, int bits, const std::string& rawOp, const std::string& destReg) override
    {
        (void)ctx;
        std::string memRegFn = (bits == 64) ? "lowering.memRegInt64Op" : "lowering.memRegUintOp";
        out.line("if (" + rawOp + ".kind != IrOpKind::Inst || " + destReg + " != lowering.regOp(" + rawOp + "))");
        out.line("    build.mov(" + destReg + ", " + memRegFn + "(" + rawOp + "));");
        out.line();
        out.line("build.not_(" + destReg + ");");
        return Operand::makeReg(bits == 64 ? TypeKind::I64 : TypeKind::U32, destReg);
    }

    Operand emitBitwiseBinOp(CodeWriter& out, EvalContext& ctx, const std::string& op, int bits, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        (void)ctx;
        std::string x64Op = (op == "and") ? "and_" : ((op == "or") ? "or_" : "xor_");
        std::string memRegFn = (bits == 64) ? "lowering.memRegInt64Op" : "lowering.memRegUintOp";
        out.line("if (" + rawOpA + ".kind != IrOpKind::Inst || " + destReg + " != lowering.regOp(" + rawOpA + "))");
        out.line("    build.mov(" + destReg + ", " + memRegFn + "(" + rawOpA + "));");
        out.line();
        out.line("build." + x64Op + "(" + destReg + ", " + memRegFn + "(" + rawOpB + "));");
        return Operand::makeReg(bits == 64 ? TypeKind::I64 : TypeKind::U32, destReg);
    }

    Operand emitMul(CodeWriter& out, EvalContext& ctx, int bits, const std::string& rawOpA, const std::string& rawOpB, const std::string& destReg) override
    {
        (void)ctx;
        (void)bits;
        out.line("build.mov(" + destReg + ", lowering.memRegInt64Op(" + rawOpA + "));");
        out.line("build.imul(" + destReg + ", lowering.memRegInt64Op(" + rawOpB + "));");
        return Operand::makeReg(TypeKind::I64, destReg);
    }

    bool emitArchOp(CodeWriter& out, EvalContext& ctx, const std::string& opName, const std::vector<std::string>& args) override
    {
        (void)ctx;
        if (opName == "x64:inc!")
        {
            if (args.size() != 1)
                throw CompileError(SourceLocation{}, "x64:inc! requires dest");
            out.line("build.inc(" + args[0] + ");");
            return true;
        }
        if (opName == "x64:mov-reg!")
        {
            if (args.size() != 2)
                throw CompileError(SourceLocation{}, "x64:mov-reg! requires dest and src");
            out.line("build.mov(" + args[0] + ", lowering.regOp(" + args[1] + "));");
            return true;
        }
        if (opName == "x64:mov-imm-32!")
        {
            if (args.size() != 2)
                throw CompileError(SourceLocation{}, "x64:mov-imm-32! requires dest and imm");
            out.line("build.mov(" + args[0] + ", lowering.intOp(" + args[1] + "));");
            return true;
        }
        if (opName == "x64:mov-imm-64!")
        {
            if (args.size() != 2)
                throw CompileError(SourceLocation{}, "x64:mov-imm-64! requires dest and imm");
            out.line("build.mov64(" + args[0] + ", lowering.int64Op(" + args[1] + "));");
            return true;
        }
        if (opName == "x64:add-reg-32!" || opName == "x64:add-reg-64!")
        {
            if (args.size() != 2)
                throw CompileError(SourceLocation{}, opName + " requires dest and src");
            out.line("build.add(" + args[0] + ", lowering.regOp(" + args[1] + "));");
            return true;
        }
        if (opName == "x64:add-imm-32!")
        {
            if (args.size() != 2)
                throw CompileError(SourceLocation{}, "x64:add-imm-32! requires dest and imm");
            out.line("build.add(" + args[0] + ", lowering.intOp(" + args[1] + "));");
            return true;
        }
        if (opName == "x64:add-imm-64!")
        {
            if (args.size() != 2)
                throw CompileError(SourceLocation{}, "x64:add-imm-64! requires dest and imm");
            out.line("build.add(" + args[0] + ", int32_t(lowering.int64Op(" + args[1] + ")));");
            return true;
        }
        if (opName == "x64:add-tmp-64!")
        {
            if (args.size() != 2)
                throw CompileError(SourceLocation{}, "x64:add-tmp-64! requires dest and imm");
            out.line("ScopedRegX64 tmp{regs, SizeX64::qword};");
            out.line("build.mov64(tmp.reg, lowering.int64Op(" + args[1] + "));");
            out.line("build.add(" + args[0] + ", tmp.reg);");
            return true;
        }
        if (opName == "x64:sub-reg-32!" || opName == "x64:sub-reg-64!")
        {
            if (args.size() != 2)
                throw CompileError(SourceLocation{}, opName + " requires dest and src");
            out.line("build.sub(" + args[0] + ", lowering.regOp(" + args[1] + "));");
            return true;
        }
        if (opName == "x64:sub-imm-32!")
        {
            if (args.size() != 2)
                throw CompileError(SourceLocation{}, "x64:sub-imm-32! requires dest and imm");
            out.line("build.sub(" + args[0] + ", lowering.intOp(" + args[1] + "));");
            return true;
        }
        if (opName == "x64:sub-imm-64!")
        {
            if (args.size() != 2)
                throw CompileError(SourceLocation{}, "x64:sub-imm-64! requires dest and imm");
            out.line("build.sub(" + args[0] + ", int32_t(lowering.int64Op(" + args[1] + ")));");
            return true;
        }
        if (opName == "x64:sub-tmp-64!")
        {
            if (args.size() != 2)
                throw CompileError(SourceLocation{}, "x64:sub-tmp-64! requires dest and imm");
            out.line("ScopedRegX64 tmp{regs, SizeX64::qword};");
            out.line("build.mov64(tmp.reg, lowering.int64Op(" + args[1] + "));");
            out.line("build.sub(" + args[0] + ", tmp.reg);");
            return true;
        }
        if (opName == "x64:lea-reg-32!" || opName == "x64:lea-reg-64!")
        {
            if (args.size() != 3)
                throw CompileError(SourceLocation{}, opName + " requires dest, base, and offset");
            out.line("build.lea(" + args[0] + ", addr[lowering.regOp(" + args[1] + ") + lowering.regOp(" + args[2] + ")]);");
            return true;
        }
        if (opName == "x64:lea-imm-32!")
        {
            if (args.size() != 3)
                throw CompileError(SourceLocation{}, "x64:lea-imm-32! requires dest, base, and offset");
            out.line("build.lea(" + args[0] + ", addr[lowering.regOp(" + args[1] + ") + lowering.intOp(" + args[2] + ")]);");
            return true;
        }
        if (opName == "x64:lea-imm-64!")
        {
            if (args.size() != 3)
                throw CompileError(SourceLocation{}, "x64:lea-imm-64! requires dest, base, and offset");
            out.line("build.lea(" + args[0] + ", addr[lowering.regOp(" + args[1] + ") + int32_t(lowering.int64Op(" + args[2] + "))]);");
            return true;
        }
        if (opName == "x64:lea-sub-32!")
        {
            if (args.size() != 3)
                throw CompileError(SourceLocation{}, "x64:lea-sub-32! requires dest, base, and offset");
            out.line("build.lea(" + args[0] + ", addr[lowering.regOp(" + args[1] + ") - lowering.intOp(" + args[2] + ")]);");
            return true;
        }
        if (opName == "x64:lea-sub-64!")
        {
            if (args.size() != 3)
                throw CompileError(SourceLocation{}, "x64:lea-sub-64! requires dest, base, and offset");
            out.line("build.lea(" + args[0] + ", addr[lowering.regOp(" + args[1] + ") - int32_t(lowering.int64Op(" + args[2] + "))]);");
            return true;
        }
        return false;
    }
};

void emitX64(std::ostream& os, const std::vector<Rule>& rules)
{
    TargetBuilderX64 target;
    compileRules(os, target, rules);
}

} // namespace Luwu::Dsl
