// What an operand kind matches: IrOpKinds, plus the IrValueKinds of Inst operands and IrConstKinds of Constant ones
struct OperandKindInfo
{
    std::vector<std::string> opKinds;
    std::vector<std::string> valueKinds;
    std::vector<std::string> constKinds;
};

static const std::map<std::string, OperandKindInfo> kOperandKinds = [] {
    std::map<std::string, OperandKindInfo> kinds = {
        // An instruction result or a constant of the same kind (float constants are Double constants)
        {"int", {{"Inst", "Constant"}, {"Int"}, {"Int"}}},
        {"int64", {{"Inst", "Constant"}, {"Int64"}, {"Int64"}}},
        {"double", {{"Inst", "Constant"}, {"Double"}, {"Double"}}},
        {"float", {{"Inst", "Constant"}, {"Float"}, {"Double"}}},
        {"tag", {{"Inst", "Constant"}, {"Tag"}, {"Tag"}}},
        {"pointer", {{"Inst"}, {"Pointer"}, {}}},
        {"tvalue", {{"Inst"}, {"Tvalue"}, {}}},

        {"const-int", {{"Constant"}, {}, {"Int"}}},
        {"const-uint", {{"Constant"}, {}, {"Uint"}}},
        {"const-int64", {{"Constant"}, {}, {"Int64"}}},
        {"const-double", {{"Constant"}, {}, {"Double"}}},
        {"const-tag", {{"Constant"}, {}, {"Tag"}}},
        {"import", {{"Constant"}, {}, {"Import"}}},

        {"Rn", {{"VmReg"}, {}, {}}},
        {"Kn", {{"VmConst"}, {}, {}}},
        {"UPn", {{"VmUpvalue"}, {}, {}}},
        {"block", {{"Block"}, {}, {}}},
        {"vmexit", {{"VmExit"}, {}, {}}},
        {"undef", {{"Undef"}, {}, {}}},
        {"cond", {{"Condition"}, {}, {}}},
        {"none", {{"None"}, {}, {}}},
        {"any", {{"Undef", "Constant", "Condition", "Inst", "Block", "VmReg", "VmConst", "VmUpvalue", "VmExit"},
                    {"Tag", "Int", "Int64", "Pointer", "Float", "Double", "Tvalue"}, {"Int", "Int64", "Uint", "Double", "Tag", "Import"}}},
    };
    // Only an instruction result of that kind
    for (const char* kind : {"int", "int64", "double", "float", "tag", "pointer", "tvalue"})
        kinds[std::string("inst-") + kind] = {{"Inst"}, kinds[kind].valueKinds, {}};
    return kinds;
}();

static std::string knownOperandKinds()
{
    std::string list;
    for (const auto& [name, info] : kOperandKinds)
        list += (list.empty() ? ":" : " :") + name;
    return list;
}

// [name :kind|:kind...]
static IrOperandDef parseOperand(const SExpr& op, const std::string& cmdName)
{
    if (op.kind != SExprKind::BracketList || op.elements.size() != 2 || !op.elements[0].isSymbol() || !op.elements[1].isKeyword())
        throw CompileError(op, "Operand must be [name :kind] or [name :kind|:kind...] in " + cmdName);

    IrOperandDef def;
    def.name = op.elements[0].text;
    def.loc = op.loc;

    const std::string& text = op.elements[1].text;
    size_t start = 0;
    while (start <= text.size())
    {
        size_t end = text.find('|', start);
        std::string part = text.substr(start, end == std::string::npos ? std::string::npos : end - start);
        if (part.size() < 2 || part[0] != ':' || !kOperandKinds.count(part.substr(1)))
            throw CompileError(op.elements[1], "Unknown operand kind '" + part + "' (expected " + knownOperandKinds() + ", joined with |)");
        if (std::find(def.kinds.begin(), def.kinds.end(), part.substr(1)) != def.kinds.end())
            throw CompileError(op.elements[1], "Duplicate operand kind " + part);
        def.kinds.push_back(part.substr(1));
        if (end == std::string::npos)
            break;
        start = end + 1;
    }
    return def;
}

static bool allowsKind(const IrOperandDef& op, const std::string& kind)
{
    return std::find(op.kinds.begin(), op.kinds.end(), kind) != op.kinds.end();
}

static std::string keywordName(const SExpr& expr)
{
    return expr.text.substr(1);
}

static bool isCommandName(const std::string& name)
{
    if (name.empty() || !std::isupper(static_cast<unsigned char>(name[0])))
        return false;
    for (char c : name)
    {
        if (!std::isupper(static_cast<unsigned char>(c)) && !std::isdigit(static_cast<unsigned char>(c)) && c != '_')
            return false;
    }
    return true;
}

// Docs on define-ircmd only go on the form itself (for now): a trailing doc on the header line moves to the form,
// like for define-rule; anywhere else inside the form is an error
static void checkClauseDocs(SExpr& expr, SExpr& form)
{
    if (expr.trailingDoc && expr.docs.empty() && expr.endLine == form.loc.line && !form.trailingDoc)
    {
        form.trailingDoc = std::move(expr.trailingDoc);
        expr.trailingDoc.reset();
    }
    if (expr.hasDocs())
        throw CompileError(expr, "Doc comments (~) inside define-ircmd aren't supported yet; put them before the form");
    for (auto& el : expr.elements)
        checkClauseDocs(el, form);
}

static int operandIndex(const IrCmdDef& cmd, const SExpr& name)
{
    if (!name.isSymbol())
        throw CompileError(name, "Expected an operand name");
    for (size_t i = 0; i < cmd.operands.size(); ++i)
    {
        if (cmd.operands[i].name == name.text)
            return int(i);
    }
    throw CompileError(name, "'" + name.text + "' isn't an operand of " + cmd.name);
}

static bool onlyKinds(const IrOperandDef& op, const std::set<std::string>& allowed)
{
    return std::all_of(op.kinds.begin(), op.kinds.end(), [&](const std::string& k) { return allowed.count(k) > 0; });
}

// A VM register: an operand name, or (+ <operand> N)
static void parseRegisterRef(const IrCmdDef& cmd, const SExpr& expr, int& op, int& offset)
{
    offset = 0;
    if (expr.isList("+"))
    {
        if (expr.elements.size() != 3 || !expr.elements[2].isNumber() || expr.elements[2].intValue < 0 || expr.elements[2].intValue > 255)
            throw CompileError(expr, "Register offsets look like (+ <operand> N) with N in 0..255");
        op = operandIndex(cmd, expr.elements[1]);
        offset = int(expr.elements[2].intValue);
        return;
    }
    op = operandIndex(cmd, expr);
}

// A register count: a number, :to-top (-1), a constant operand, or (low-byte <operand>)
static IrEffectCountDef parseCount(const IrCmdDef& cmd, const SExpr& expr)
{
    IrEffectCountDef count;
    if (expr.isNumber())
    {
        count.kind = "literal";
        count.value = int(expr.intValue);
    }
    else if (expr.isKeyword(":to-top"))
    {
        count.kind = "literal";
        count.value = -1;
    }
    else if (expr.isList("low-byte") && expr.elements.size() == 2)
    {
        count.kind = "low-byte";
        count.value = operandIndex(cmd, expr.elements[1]);
        if (!onlyKinds(cmd.operands[count.value], {"const-int"}))
            throw CompileError(expr, "(low-byte ...) needs a :const-int operand");
    }
    else if (expr.isSymbol())
    {
        count.value = operandIndex(cmd, expr);
        const IrOperandDef& op = cmd.operands[count.value];
        if (onlyKinds(op, {"const-int"}))
            count.kind = "int";
        else if (onlyKinds(op, {"const-uint"}))
            count.kind = "uint";
        else
            throw CompileError(expr, "Count operand '" + op.name + "' has to be :const-int or :const-uint");
    }
    else
    {
        throw CompileError(expr, "Expected a count: a number, :to-top, a constant operand or (low-byte <operand>)");
    }
    return count;
}

static bool allowsRn(const IrOperandDef& op)
{
    return std::find(op.kinds.begin(), op.kinds.end(), "Rn") != op.kinds.end();
}

static void parseEffectClause(IrCmdDef& cmd, const SExpr& clause)
{
    const std::string& kind = clause.elements[0].text;
    if (clause.elements.size() < 2)
        throw CompileError(clause, kind + " needs at least one effect (or :none)");

    // In vm-effects and location-tracking, :none means "no effects"; in dead-store it's one of the kinds
    auto isNone = [](const SExpr& e) { return e.isKeyword(":none"); };
    bool none = kind != "dead-store" && std::any_of(clause.elements.begin() + 1, clause.elements.end(), isNone);
    if (none && clause.elements.size() != 2)
        throw CompileError(clause, kind + " :none can't be combined with other effects");

    auto hookName = [&](const SExpr& item) {
        if (item.elements.size() != 2 || !item.elements[1].isSymbol())
            throw CompileError(item, "Hooks look like (" + item.elements[0].text + " <name>)");
        return item.elements[1].text;
    };

    if (kind == "vm-effects")
    {
        cmd.hasVmEffects = true;
        for (size_t i = 1; i < clause.elements.size() && !none; ++i)
        {
            const SExpr& item = clause.elements[i];
            if (!item.isList() || item.elements.empty() || !item.elements[0].isSymbol())
                throw CompileError(item, "vm-effects items look like (use a), (def-range a count), (hook <name>) or :none");

            const std::string& effect = item.elements[0].text;
            if (effect == "hook")
            {
                if (!cmd.vmHook.empty())
                    throw CompileError(item, "Only one vm-effects hook per command");
                cmd.vmHook = hookName(item);
                continue;
            }

            static const std::set<std::string> kOneArg = {"use", "maybe-use", "def", "maybe-def", "use-varargs"};
            static const std::set<std::string> kRange = {"use-range", "def-range"};
            if (!kOneArg.count(effect) && !kRange.count(effect))
                throw CompileError(item.elements[0], "Unknown vm-effects item '" + effect + "'");
            if (item.elements.size() != (kRange.count(effect) ? 3u : 2u))
                throw CompileError(item, kRange.count(effect) ? "(" + effect + " <register> <count>)" : "(" + effect + " <register>)");

            IrVmEffectDef def;
            def.kind = effect;
            def.loc = item.loc;
            parseRegisterRef(cmd, item.elements[1], def.op, def.offset);
            if (kRange.count(effect))
                def.count = parseCount(cmd, item.elements[2]);
            if (def.offset != 0 && (effect == "maybe-use" || effect == "maybe-def"))
                throw CompileError(item, effect + " doesn't take an offset");

            // use/def and the ranges read the operand as a VM register; maybe-* only acts when it is one
            const IrOperandDef& op = cmd.operands[def.op];
            if (effect.rfind("maybe-", 0) == 0 ? !allowsRn(op) : !onlyKinds(op, {"Rn"}))
                throw CompileError(item, std::string("Operand '") + op.name + "' " +
                    (effect.rfind("maybe-", 0) == 0 ? "can't be a VM register, so " + effect + " never applies" : "can be something other than :Rn; use maybe-use/maybe-def"));

            cmd.vmEffects.push_back(def);
        }

        // Uses come first: visitors rely on seeing all of an instruction's uses before its defs
        std::stable_partition(cmd.vmEffects.begin(), cmd.vmEffects.end(), [](const IrVmEffectDef& e) { return e.kind.find("use") != std::string::npos; });
    }
    else if (kind == "location-tracking")
    {
        cmd.hasLocationTracking = true;
        for (size_t i = 1; i < clause.elements.size() && !none; ++i)
        {
            const SExpr& item = clause.elements[i];
            if (!item.isList() || item.elements.empty() || !item.elements[0].isSymbol())
                throw CompileError(item, "location-tracking items look like (invalidate a), (restore-from-load a), (hook-before <name>) or :none");

            const std::string& effect = item.elements[0].text;
            if (effect == "hook-before" || effect == "hook-after")
            {
                std::string& hook = effect == "hook-before" ? cmd.locationBeforeHook : cmd.locationAfterHook;
                if (!hook.empty())
                    throw CompileError(item, "Only one " + effect + " per command");
                hook = hookName(item);
                continue;
            }

            IrLocationEffectDef def;
            def.kind = effect;
            if (effect == "invalidate" || effect == "invalidate-keep-values" || effect == "restore-from-load")
            {
                if (item.elements.size() != 2)
                    throw CompileError(item, "(" + effect + " <operand>)");
                def.op = operandIndex(cmd, item.elements[1]);
            }
            else if (effect == "invalidate-range")
            {
                if (item.elements.size() != 3)
                    throw CompileError(item, "(invalidate-range <register> <count>)");
                parseRegisterRef(cmd, item.elements[1], def.op, def.offset);
                if (!onlyKinds(cmd.operands[def.op], {"Rn"}))
                    throw CompileError(item, "invalidate-range needs a :Rn operand");
                def.count = parseCount(cmd, item.elements[2]);
            }
            else if (effect == "restore-from-store")
            {
                if (item.elements.size() != 3)
                    throw CompileError(item, "(restore-from-store <destination> <value>)");
                def.op = operandIndex(cmd, item.elements[1]);
                def.valueOp = operandIndex(cmd, item.elements[2]);
            }
            else
            {
                throw CompileError(item.elements[0], "Unknown location-tracking item '" + effect + "'");
            }

            bool after = effect.rfind("restore-", 0) == 0;
            std::vector<IrLocationEffectDef>& list = after ? cmd.locationAfter : cmd.locationBefore;
            if (!list.empty())
                throw CompileError(item, std::string("Only one location-tracking effect ") + (after ? "after" : "before") + " lowering per command");
            list.push_back(def);
        }
    }
    else // dead-store
    {
        bool primary = false;
        for (size_t i = 1; i < clause.elements.size(); ++i)
        {
            const SExpr& item = clause.elements[i];
            auto setPrimary = [&](const std::string& value) {
                if (primary)
                    throw CompileError(item, "dead-store takes one of :visit, :none, :live-ins, :live-ins-no-exit-sync, :live-outs, :allocation, (hook <name>)");
                primary = true;
                cmd.deadStore = value;
            };

            if (item.isKeyword())
            {
                static const std::set<std::string> kKinds = {"visit", "none", "live-ins", "live-ins-no-exit-sync", "live-outs", "allocation"};
                if (!kKinds.count(keywordName(item)))
                    throw CompileError(item, "Unknown dead-store kind " + item.text);
                setPrimary(keywordName(item));
                continue;
            }
            if (!item.isList() || item.elements.empty() || !item.elements[0].isSymbol())
                throw CompileError(item, "dead-store items look like :live-ins, (writes-allocation a), (store-hint a v :double) or (hook <name>)");

            const std::string& effect = item.elements[0].text;
            if (effect == "hook")
            {
                setPrimary("hook");
                cmd.deadStoreHook = hookName(item);
            }
            else if (effect == "writes-allocation")
            {
                if (item.elements.size() != 2)
                    throw CompileError(item, "(writes-allocation <pointer operand>)");
                cmd.allocationWriteOp = operandIndex(cmd, item.elements[1]);
            }
            else if (effect == "store-hint")
            {
                static const std::map<std::string, std::string> kHintKinds = {
                    {"double", "Double"}, {"int", "Int"}, {"int64", "Int64"}, {"pointer", "Pointer"}, {"tvalue", "Tvalue"}, {"inferred", "Unknown"}};
                if (item.elements.size() != 4 || !item.elements[3].isKeyword() || !kHintKinds.count(keywordName(item.elements[3])))
                    throw CompileError(item, "(store-hint <destination> <value> :double|:int|:int64|:pointer|:tvalue|:inferred)");
                cmd.storeHintDest = operandIndex(cmd, item.elements[1]);
                cmd.storeHintValue = operandIndex(cmd, item.elements[2]);
                cmd.storeHintKind = kHintKinds.at(keywordName(item.elements[3]));
            }
            else
            {
                throw CompileError(item.elements[0], "Unknown dead-store item '" + effect + "'");
            }
        }
    }
}

// Effects every command of a kind needs, so a forgotten declaration is an error here instead of a runtime assert
static void checkEffects(IrCmdDef& cmd, const SExpr& form)
{
    bool baseRn = std::any_of(cmd.operands.begin(), cmd.operands.end(), allowsRn);
    bool anyRn = baseRn;
    for (const auto& group : cmd.targetSpecific)
        anyRn = anyRn || std::any_of(group.operands.begin(), group.operands.end(), allowsRn);

    if (baseRn && !cmd.hasVmEffects)
        throw CompileError(form, cmd.name + " can have VM register operands, so it needs (vm-effects ...) (or (vm-effects :none))");
    // Pseudo-instructions are never lowered, so value location tracking never sees them
    if (anyRn && !cmd.hasLocationTracking && cmd.cls != "pseudo")
        throw CompileError(form, cmd.name + " can have VM register operands, so it needs (location-tracking ...) (or (location-tracking :none))");

    if (cmd.deadStore == "live-ins" || cmd.deadStore == "live-ins-no-exit-sync")
    {
        if (cmd.cls != "guard")
            throw CompileError(form, cmd.name + ": dead-store :" + cmd.deadStore + " is for guards");
        for (size_t i = 0; i < cmd.operands.size(); ++i)
        {
            const auto& kinds = cmd.operands[i].kinds;
            if (std::find(kinds.begin(), kinds.end(), "block") != kinds.end() || std::find(kinds.begin(), kinds.end(), "vmexit") != kinds.end())
            {
                if (cmd.deadStoreTarget >= 0)
                    throw CompileError(form, cmd.name + " has several target operands; dead-store :live-ins needs exactly one");
                cmd.deadStoreTarget = int(i);
            }
        }
        if (cmd.deadStoreTarget < 0)
            throw CompileError(form, cmd.name + " has no :block/:vmexit operand for dead-store :live-ins");
    }
    if (cmd.cls == "guard" && cmd.deadStore != "live-ins" && cmd.deadStore != "live-ins-no-exit-sync" && cmd.deadStore != "hook")
        throw CompileError(form, cmd.name + " is a guard, so dead-store elimination has to check its target's live-ins: (dead-store :live-ins)");
    if (cmd.heapEffects.count("may-gc") && cmd.deadStore != "visit")
        throw CompileError(form, cmd.name + ": dead-store elimination only flushes GC object registers for :may-gc commands it visits (dead-store :visit)");
    if (cmd.deadStore == "live-outs" && cmd.cls != "terminator")
        throw CompileError(form, cmd.name + ": dead-store :live-outs is for terminators");
}

static IrCmdDef parseIrCmd(const SExpr& original)
{
    SExpr form = original;
    if (form.elements.size() < 2 || !form.elements[1].isSymbol() || !isCommandName(form.elements[1].text))
        throw CompileError(form, "define-ircmd needs an UPPER_SNAKE command name: (define-ircmd NAME <clause>...)");

    for (size_t i = 1; i < form.elements.size(); ++i)
        checkClauseDocs(form.elements[i], form);

    IrCmdDef cmd;
    cmd.name = form.elements[1].text;
    cmd.loc = form.elements[1].loc;
    cmd.docs = form.docs;
    if (form.trailingDoc)
        cmd.docs.push_back(*form.trailingDoc);

    std::set<std::string> seenClauses;
    std::vector<const SExpr*> effectClauses; // parsed once the operands are known
    for (size_t i = 2; i < form.elements.size(); ++i)
    {
        const SExpr& clause = form.elements[i];
        if (!clause.isList() || clause.elements.empty() || !clause.elements[0].isSymbol())
            throw CompileError(clause, "define-ircmd clause must be a list like (result :int)");

        const std::string& kind = clause.elements[0].text;
        if (!seenClauses.insert(kind).second)
            throw CompileError(clause, "Duplicate " + kind + " clause in define-ircmd " + cmd.name);

        auto keywordArgs = [&](const std::set<std::string>& allowed, const char* what) {
            std::set<std::string> result;
            for (size_t j = 1; j < clause.elements.size(); ++j)
            {
                const SExpr& arg = clause.elements[j];
                if (!arg.isKeyword() || !allowed.count(keywordName(arg)))
                {
                    std::string list;
                    for (const auto& a : allowed)
                        list += (list.empty() ? ":" : ", :") + a;
                    throw CompileError(arg, std::string("Unknown ") + what + " '" + arg.text + "' (expected one of " + list + ")");
                }
                if (!result.insert(keywordName(arg)).second)
                    throw CompileError(arg, std::string("Duplicate ") + what + " " + arg.text);
            }
            return result;
        };

        if (kind == "operands")
        {
            std::set<std::string> names;
            for (size_t j = 1; j < clause.elements.size(); ++j)
            {
                IrOperandDef op = parseOperand(clause.elements[j], cmd.name);
                if (!names.insert(op.name).second)
                    throw CompileError(clause.elements[j], "Duplicate operand '" + op.name + "' in " + cmd.name);

                // Optional operands are trailing: once one can be absent, all later ones can be too
                if (!cmd.operands.empty() && allowsKind(cmd.operands.back(), "none") && !allowsKind(op, "none"))
                    throw CompileError(clause.elements[j], "Operand '" + op.name + "' follows optional operand '" + cmd.operands.back().name +
                        "', so it has to allow :none as well");
                cmd.operands.push_back(std::move(op));
            }
            if (cmd.operands.size() > kMaxOperands)
                throw CompileError(clause, cmd.name + " has " + std::to_string(cmd.operands.size()) + " operands; IR instructions have at most 7 (A..G)");
        }
        else if (kind == "target-specific" || kind == "flag-specific")
        {
            // [:key [operand :kinds]...] groups; operands are resolved after all clauses are read
            bool byTarget = kind == "target-specific";
            const std::vector<std::string>& keys = byTarget ? knownTargets() : kOperandFlags;
            std::vector<IrOperandExtras>& groups = byTarget ? cmd.targetSpecific : cmd.flagSpecific;

            for (size_t j = 1; j < clause.elements.size(); ++j)
            {
                const SExpr& group = clause.elements[j];
                if (group.kind != SExprKind::BracketList || group.elements.empty() || !group.elements[0].isKeyword())
                    throw CompileError(group, kind + " groups look like [" + (byTarget ? ":x64" : ":DebugLuauAbortingChecks") + " [operand :kind]...]");

                std::string key = keywordName(group.elements[0]);
                if (std::find(keys.begin(), keys.end(), key) == keys.end())
                {
                    std::string list;
                    for (const auto& k : keys)
                        list += (list.empty() ? ":" : ", :") + k;
                    throw CompileError(group.elements[0], std::string("Unknown ") + (byTarget ? "target" : "flag") + " " + group.elements[0].text + " (expected " + list + ")");
                }
                if (std::any_of(groups.begin(), groups.end(), [&](const IrOperandExtras& g) { return g.key == key; }))
                    throw CompileError(group.elements[0], "Duplicate " + kind + " group for " + group.elements[0].text);
                if (group.elements.size() < 2)
                    throw CompileError(group, "The " + group.elements[0].text + " group needs at least one [operand :kind]");

                IrOperandExtras extras;
                extras.key = key;
                extras.loc = group.loc;
                for (size_t k = 1; k < group.elements.size(); ++k)
                    extras.operands.push_back(parseOperand(group.elements[k], cmd.name));
                groups.push_back(std::move(extras));
            }
            if (groups.empty())
                throw CompileError(clause, kind + " needs at least one [" + (byTarget ? ":x64" : ":DebugLuauAbortingChecks") + " [operand :kind]...] group");
        }
        else if (kind == "result")
        {
            if (clause.elements.size() != 2 || !clause.elements[1].isKeyword() || !kResultKinds.count(keywordName(clause.elements[1])))
                throw CompileError(clause, "result expects one of :tag, :int, :int64, :pointer, :float, :double, :tvalue, :unknown");
            cmd.result = kResultKinds.at(keywordName(clause.elements[1]));
        }
        else if (kind == "class")
        {
            if (clause.elements.size() != 2 || !clause.elements[1].isKeyword() || !kClasses.count(keywordName(clause.elements[1])))
                throw CompileError(clause, "class expects one of :value, :effect, :guard, :terminator, :pseudo");
            cmd.cls = keywordName(clause.elements[1]);
        }
        else if (kind == "flags")
        {
            cmd.flags = keywordArgs(kFlags, "flag");
        }
        else if (kind == "heap-effects")
        {
            cmd.heapEffects = keywordArgs(kHeapEffects, "heap effect");
        }
        else if (kind == "vm-effects" || kind == "location-tracking" || kind == "dead-store")
        {
            effectClauses.push_back(&clause);
        }
        else if (kind == "lowering")
        {
            if (clause.elements.size() != 2)
                throw CompileError(clause, "lowering expects a single rule call: (lowering (<rule> <args>...))");
            const SExpr& call = clause.elements[1];
            if (call.isKeyword(":semantics"))
                throw CompileError(call, "(lowering :semantics) isn't supported yet; name a define-rule");
            if (!call.isList() || call.kind != SExprKind::List || call.elements.empty() || !call.elements[0].isSymbol())
                throw CompileError(call, "lowering expects a rule call: (lowering (<rule> <args>...))");

            IrCmdLowering lowering;
            lowering.rule = call.elements[0].text;
            lowering.args.assign(call.elements.begin() + 1, call.elements.end());
            lowering.loc = call.loc;
            cmd.lowering = std::move(lowering);
        }
        else
        {
            throw CompileError(clause.elements[0], "Unknown define-ircmd clause '" + kind + "' (expected operands, target-specific, flag-specific, result, class, flags, heap-effects, vm-effects, location-tracking, dead-store or lowering)");
        }
    }

    for (const auto* groups : {&cmd.targetSpecific, &cmd.flagSpecific})
    {
        for (const auto& group : *groups)
        {
            std::set<std::string> seen;
            for (const auto& extra : group.operands)
            {
                if (std::none_of(cmd.operands.begin(), cmd.operands.end(), [&](const IrOperandDef& op) { return op.name == extra.name; }))
                    throw CompileError(extra.loc, "'" + extra.name + "' isn't an operand of " + cmd.name);
                if (!seen.insert(extra.name).second)
                    throw CompileError(extra.loc, "Duplicate extra kinds for '" + extra.name + "' in the :" + group.key + " group");
            }
        }
    }

    if (cmd.cls.empty())
        throw CompileError(form, cmd.name + " needs a (class ...) clause");

    for (const SExpr* clause : effectClauses)
        parseEffectClause(cmd, *clause);
    checkEffects(cmd, form);
    if (cmd.cls == "value" && cmd.result.empty())
        throw CompileError(form, cmd.name + " is a :value command but has no (result ...)");
    if (cmd.cls == "effect" && !cmd.result.empty())
        throw CompileError(form, cmd.name + " is an :effect command but has a result; use :value");
    if (cmd.cls == "pseudo" && cmd.lowering)
        throw CompileError(cmd.lowering->loc, cmd.name + " is a pseudo-instruction and isn't lowered");
    if (cmd.cls != "pseudo" && !cmd.lowering)
        throw CompileError(form, cmd.name + " needs a (lowering (<rule> <args>...)) clause");

    return cmd;
}

std::vector<IrCmdDef> parseIrCmds(const std::vector<SExpr>& program)
{
    std::vector<IrCmdDef> cmds;
    std::unordered_map<std::string, SourceLocation> seen;

    for (const auto& form : program)
    {
        if (!form.isList("define-ircmd"))
            continue;

        IrCmdDef cmd = parseIrCmd(form);
        auto [prev, inserted] = seen.emplace(cmd.name, cmd.loc);
        if (!inserted)
            throw CompileError(cmd.loc, "Duplicate define-ircmd " + cmd.name + " (previously defined at " + prev->second.toString() + ")");

        // A value-initialized IrInst is command 0, which should be the no-op
        if (cmd.name == "NOP" && !cmds.empty())
            throw CompileError(cmd.loc, "NOP must be the first define-ircmd, so a zero-initialized instruction is a no-op");

        cmds.push_back(std::move(cmd));
    }

    if (cmds.size() > kMaxCommands)
        throw CompileError(cmds[kMaxCommands].loc, "More than 256 IR commands; IrCmd is a uint8_t");

    return cmds;
}

// The operand kinds a rule parameter can read: e.g. an :int parameter reads with intOp, which only handles constants
static const std::map<std::string, std::set<std::string>> kParamKinds = [] {
    std::set<std::string> instKinds;
    for (const auto& [name, info] : kOperandKinds)
    {
        if (name.rfind("inst-", 0) == 0)
            instKinds.insert(name);
    }
    return std::map<std::string, std::set<std::string>>{
        {"int", {"const-int"}},
        {"uint", {"const-uint"}},
        {"tag", {"const-tag"}},
        {"cond", {"cond"}},
        {"upvalue", {"UPn"}},
        {"reg", instKinds},
        {"label", {"block", "vmexit", "undef"}},
    };
}();

static void checkParamKinds(const IrCmdDef& cmd, const IrOperandDef& op, const RuleParam& param, const SExpr& arg)
{
    auto allowed = kParamKinds.find(param.type);
    if (allowed == kParamKinds.end())
        return; // :op parameters handle whatever they get

    auto check = [&](const IrOperandDef& def, const std::string& where) {
        for (const auto& kind : def.kinds)
        {
            // An absent optional operand is never read unless the rule checks it's there
            if (kind != "none" && !allowed->second.count(kind))
            {
                throw CompileError(arg, cmd.name + " operand '" + op.name + "' can be :" + kind + where + ", but rule parameter '" + param.name +
                    "' is :" + param.type + ", which can't read that; use an :op parameter or narrow the operand's kinds");
            }
        }
    };
    check(op, "");
    for (const auto& group : cmd.targetSpecific)
        for (const auto& extra : group.operands)
            if (extra.name == op.name)
                check(extra, " (on " + group.key + ")");
    for (const auto& group : cmd.flagSpecific)
        for (const auto& extra : group.operands)
            if (extra.name == op.name)
                check(extra, " (with " + group.key + ")");
}

std::vector<LoweringInstance> linkLowerings(const std::vector<IrCmdDef>& cmds, const std::vector<Rule>& rules)
{
    std::unordered_map<std::string, size_t> ruleIndex;
    for (size_t i = 0; i < rules.size(); ++i)
        ruleIndex[rules[i].name] = i;

    std::vector<std::vector<LoweringInstance>> byRule(rules.size());

    for (const auto& cmd : cmds)
    {
        if (!cmd.lowering)
            continue;

        const IrCmdLowering& lowering = *cmd.lowering;
        auto it = ruleIndex.find(lowering.rule);
        if (it == ruleIndex.end())
            throw CompileError(lowering.loc, cmd.name + " is lowered by '" + lowering.rule + "', which isn't a define-rule");

        const Rule& rule = rules[it->second];
        if (lowering.args.size() != rule.params.size())
        {
            throw CompileError(lowering.loc, "Rule " + rule.name + " takes " + std::to_string(rule.params.size()) + " argument(s), but " + cmd.name +
                " passes " + std::to_string(lowering.args.size()) + " (rule defined at " + rule.loc.toString() + ")");
        }

        LoweringInstance instance;
        instance.cmdName = cmd.name;
        instance.rule = &rule;
        for (size_t i = 0; i < lowering.args.size(); ++i)
        {
            const SExpr& arg = lowering.args[i];
            if (arg.isSymbol())
            {
                auto op = std::find_if(cmd.operands.begin(), cmd.operands.end(), [&](const IrOperandDef& o) { return o.name == arg.text; });
                if (op == cmd.operands.end())
                {
                    std::string list;
                    for (const auto& o : cmd.operands)
                        list += (list.empty() ? "" : ", ") + o.name;
                    throw CompileError(arg, "'" + arg.text + "' isn't an operand of " + cmd.name + " (operands: " + (list.empty() ? "none" : list) + ")");
                }
                checkParamKinds(cmd, *op, rule.params[i], arg);
                instance.operandIndex.push_back(int(op - cmd.operands.begin()));
                instance.literals.emplace_back();
            }
            else if (arg.isNumber() || arg.isKeyword())
            {
                instance.operandIndex.push_back(-1);
                instance.literals.push_back(arg);
            }
            else
            {
                throw CompileError(arg, "Lowering arguments must be operand names or number/keyword literals");
            }
        }

        byRule[it->second].push_back(std::move(instance));
    }

    // Rule order (then command order) keeps the generated lowering functions in the order of the rules
    std::vector<LoweringInstance> instances;
    for (size_t i = 0; i < rules.size(); ++i)
    {
        if (byRule[i].empty())
            throw CompileError(rules[i].loc, "define-rule " + rules[i].name + " isn't used by any define-ircmd (add a (lowering (" + rules[i].name + " ...)) clause)");
        for (auto& instance : byRule[i])
            instances.push_back(std::move(instance));
    }
    return instances;
}

std::vector<DispatchEntry> loweringDispatch(const std::vector<IrCmdDef>& cmds)
{
    std::vector<DispatchEntry> dispatch;
    for (const auto& cmd : cmds)
        dispatch.push_back({cmd.name, cmd.cls != "pseudo"});
    return dispatch;
}

static bool hasSideEffects(const IrCmdDef& cmd)
{
    // Today's heuristic: an instruction without a result must be there for its side effects
    if (cmd.cls == "pseudo")
        return false;
    if (cmd.flags.count("deprecated/has-side-effects"))
        return true;
    return cmd.result.empty();
}

static void openNamespaces(CodeWriter& out)
{
    out.line("namespace Luau");
    out.line("{");
    out.line("namespace CodeGen");
    out.line("{");
}

static void closeNamespaces(CodeWriter& out)
{
    out.line("} // namespace CodeGen");
    out.line("} // namespace Luau");
}

// case labels line up with the switch's braces, like the hand-written switches
template <typename Fn>
static void switchOnCmd(CodeWriter& out, Fn&& fn)
{
    out.line("switch (cmd)");
    out.line("{");
    fn();
    out.line("}");
}

template <typename Pred>
static void emitPredicate(CodeWriter& out, const std::vector<IrCmdDef>& cmds, const std::string& name, const char* comment, Pred&& pred)
{
    out.line();
    out.line(std::string("// ") + comment);
    out.block("inline bool " + name + "(IrCmd cmd)", [&]() {
        switchOnCmd(out, [&]() {
            bool any = false;
            for (const auto& cmd : cmds)
            {
                if (!pred(cmd))
                    continue;
                out.line("case IrCmd::" + cmd.name + ":");
                any = true;
            }
            if (any)
            {
                out.indent();
                out.line("return true;");
                out.dedent();
            }
            out.line("default:");
            out.indent();
            out.line("return false;");
            out.dedent();
        });
    });
}

static std::string upper(std::string text)
{
    for (char& c : text)
        c = char(std::toupper(static_cast<unsigned char>(c)));
    return text;
}

// IrCmdOperands field names: targetX64, flagDebugLuauAbortingChecks
static std::string targetField(const std::string& target)
{
    return "target" + upper(target);
}

static std::string flagField(const std::string& flag)
{
    return "flag" + flag;
}

// {opKinds, valueKinds, constKinds} initializer for the union of an operand's kinds
static std::string operandSpecInit(const std::vector<std::string>& kinds)
{
    std::vector<std::string> opKinds, valueKinds, constKinds;
    auto add = [](std::vector<std::string>& to, const std::vector<std::string>& from) {
        for (const auto& k : from)
            if (std::find(to.begin(), to.end(), k) == to.end())
                to.push_back(k);
    };
    for (const auto& kind : kinds)
    {
        const OperandKindInfo& info = kOperandKinds.at(kind);
        add(opKinds, info.opKinds);
        add(valueKinds, info.valueKinds);
        add(constKinds, info.constKinds);
    }

    auto list = [](const char* fn, const char* type, const std::vector<std::string>& values) {
        std::string text = std::string(fn) + "(";
        for (size_t i = 0; i < values.size(); ++i)
            text += (i ? ", " : "") + std::string(type) + "::" + values[i];
        return text + ")";
    };
    return "{" + list("irOpKinds", "IrOpKind", opKinds) + ", " + list("irValueKinds", "IrValueKind", valueKinds) + ", " +
           list("irConstKinds", "IrConstKind", constKinds) + "}";
}

static void emitOperandTable(CodeWriter& out, const std::vector<IrCmdDef>& cmds)
{
    out.line();
    out.line("// Operand kinds of each command, from (operands ...): bits per IrOpKind, plus the IrValueKinds an Inst operand and the");
    out.line("// IrConstKinds a Constant operand may have");
    out.block("struct IrOperandSpec", [&]() {
        out.line("uint16_t opKinds = 0;");
        out.line("uint16_t valueKinds = 0;");
        out.line("uint8_t constKinds = 0;");
    });
    out.raw(";\n\n");
    out.block("struct IrCmdOperands", [&]() {
        out.line("uint8_t count = 0;");
        out.line("IrOperandSpec ops[7];");
        for (const auto& target : knownTargets())
            out.line("IrOperandSpec " + targetField(target) + "[7]; // extra kinds when compiling for " + upper(target) + " (target-specific)");
        for (const auto& flag : kOperandFlags)
            out.line("IrOperandSpec " + flagField(flag) + "[7]; // extra kinds with FFlag::" + flag + " (flag-specific)");
    });
    out.raw(";\n\n");
    for (const auto& helper : {std::pair{"irOpKinds", "uint16_t"}, std::pair{"irValueKinds", "uint16_t"}, std::pair{"irConstKinds", "uint8_t"}})
    {
        std::string width = helper.second;
        out.line("template<typename... Kinds>");
        out.block("constexpr " + width + " " + helper.first + "(Kinds... kinds)", [&]() {
            out.line("return " + width + "((0u | ... | (1u << unsigned(kinds))));");
        });
        out.line();
    }

    // One array per known target and flag, in the order the struct declares them
    auto extrasInit = [&](const IrCmdDef& cmd, const std::vector<IrOperandExtras>& groups, const std::string& key) {
        auto group = std::find_if(groups.begin(), groups.end(), [&](const IrOperandExtras& g) { return g.key == key; });
        if (group == groups.end())
            return std::string("{}");
        std::string text = "{";
        for (size_t i = 0; i < cmd.operands.size(); ++i)
        {
            auto it = std::find_if(group->operands.begin(), group->operands.end(), [&](const IrOperandDef& e) { return e.name == cmd.operands[i].name; });
            text += (i ? ", " : "") + (it == group->operands.end() ? std::string("{}") : operandSpecInit(it->kinds));
        }
        return text + "}";
    };

    out.line("// Indexed by IrCmd: the enum and this table are both in declaration order");
    out.line("inline constexpr IrCmdOperands kIrCmdOperands[] = {");
    out.indent();
    for (const auto& cmd : cmds)
    {
        std::string ops = "{";
        for (size_t i = 0; i < cmd.operands.size(); ++i)
            ops += (i ? ", " : "") + operandSpecInit(cmd.operands[i].kinds);
        ops += "}";
        out.line("// " + cmd.name);
        std::string extras;
        for (const auto& target : knownTargets())
            extras += ", " + extrasInit(cmd, cmd.targetSpecific, target);
        for (const auto& flag : kOperandFlags)
            extras += ", " + extrasInit(cmd, cmd.flagSpecific, flag);
        out.line("{" + std::to_string(cmd.operands.size()) + ", " + ops + extras + "},");
    }
    out.dedent();
    out.line("};");
    out.line("static_assert(sizeof(kIrCmdOperands) / sizeof(kIrCmdOperands[0]) == kIrCmdCount, \"one entry per IrCmd\");");
    out.line();
    out.block("inline const IrCmdOperands& getCmdOperands(IrCmd cmd)", [&]() {
        out.line("return kIrCmdOperands[unsigned(cmd)];");
    });
}

void emitIrCmdInfo(std::ostream& os, const std::vector<IrCmdDef>& cmds)
{
    CodeWriter out(os);
    out.raw(kHeaderBanner);
    out.raw("// Per-command IR information, from the define-ircmd declarations in Luna/defs/ir (included by Luau/IrUtils.h)\n"
            "#pragma once\n\n"
            "#include \"Luau/Common.h\"\n"
            "#include \"Luau/IrData.h\"\n\n"
            "#include <stddef.h>\n\n");
    openNamespaces(out);
    out.line();

    out.line("// Every command, in declaration order");
    out.line("inline constexpr IrCmd kIrCmds[] = {");
    out.indent();
    for (const auto& cmd : cmds)
        out.line("IrCmd::" + cmd.name + ",");
    out.dedent();
    out.line("};");
    out.line();
    out.line("inline constexpr size_t kIrCmdCount = " + std::to_string(cmds.size()) + ";");
    out.line("static_assert(kIrCmdCount <= 256, \"IrCmd is a uint8_t\");");

    // Full switches (no default): -Wswitch then checks that every IrCmd enumerator is declared in Luna
    out.line();
    out.block("inline const char* getCmdName(IrCmd cmd)", [&]() {
        switchOnCmd(out, [&]() {
            for (const auto& cmd : cmds)
            {
                out.line("case IrCmd::" + cmd.name + ":");
                out.indent();
                out.line("return \"" + cmd.name + "\";");
                out.dedent();
            }
        });
        out.line();
        out.line("LUAU_UNREACHABLE();");
    });

    out.line();
    out.block("inline IrValueKind getCmdValueKind(IrCmd cmd)", [&]() {
        switchOnCmd(out, [&]() {
            // One case group per result kind, in order of first use
            std::vector<std::string> kinds;
            for (const auto& cmd : cmds)
            {
                std::string kind = cmd.result.empty() ? "None" : cmd.result;
                if (std::find(kinds.begin(), kinds.end(), kind) == kinds.end())
                    kinds.push_back(kind);
            }
            for (const auto& kind : kinds)
            {
                for (const auto& cmd : cmds)
                {
                    if ((cmd.result.empty() ? "None" : cmd.result) == kind)
                        out.line("case IrCmd::" + cmd.name + ":");
                }
                out.indent();
                out.line("return IrValueKind::" + kind + ";");
                out.dedent();
            }
        });
        out.line();
        out.line("LUAU_UNREACHABLE();");
    });

    out.line();
    out.line("// Commands with a (result ...)");
    out.block("inline bool hasResult(IrCmd cmd)", [&]() {
        out.line("return getCmdValueKind(cmd) != IrValueKind::None;");
    });

    emitPredicate(out, cmds, "isBlockTerminator", "Instructions that end a block (class :terminator)",
        [](const IrCmdDef& c) { return c.cls == "terminator"; });
    emitPredicate(out, cmds, "isNonTerminatingJump", "Instructions that may branch to another block but otherwise continue (class :guard)",
        [](const IrCmdDef& c) { return c.cls == "guard"; });
    emitPredicate(out, cmds, "isPseudo", "Instructions that are used for internal needs and are not a part of final lowering (class :pseudo)",
        [](const IrCmdDef& c) { return c.cls == "pseudo"; });
    emitPredicate(out, cmds, "hasSideEffects",
        "Instructions without a result are assumed to have side effects (otherwise they'd be useless), plus the ones flagged "
        ":deprecated/has-side-effects; pseudo-instructions have none",
        [](const IrCmdDef& c) { return hasSideEffects(c); });
    emitPredicate(out, cmds, "canInvalidateSafeEnv", "Instructions that can run user code and so invalidate the safe environment (heap-effects :invalidates-safe-env)",
        [](const IrCmdDef& c) { return c.heapEffects.count("invalidates-safe-env") > 0; });
    emitPredicate(out, cmds, "isUnsafeToSink",
        "Result-producing instructions that pass !hasSideEffects but are still unsafe to sink into ExitSync blocks (flag "
        ":deprecated/is-unsafe-to-sink)",
        [](const IrCmdDef& c) { return c.flags.count("deprecated/is-unsafe-to-sink") > 0; });
    emitPredicate(out, cmds, "producesDirtyHighRegisterBits", "Instructions whose result register may have garbage in its high bits (flag :dirty-high-bits)",
        [](const IrCmdDef& c) { return c.flags.count("dirty-high-bits") > 0; });

    if (!cmds.empty())
        emitOperandTable(out, cmds);

    out.line();
    closeNamespaces(out);
}

static std::string pascalCase(const std::string& name)
{
    std::string result;
    bool upperNext = true;
    for (char c : name)
    {
        if (c == '-' || c == '_')
        {
            upperNext = true;
            continue;
        }
        result += upperNext ? char(std::toupper(static_cast<unsigned char>(c))) : c;
        upperNext = false;
    }
    return result;
}

static std::string countInit(const IrEffectCountDef& count)
{
    if (count.kind == "none")
        return "{}";
    static const std::map<std::string, std::string> kKinds = {
        {"literal", "Literal"}, {"int", "IntOperand"}, {"uint", "UintOperand"}, {"low-byte", "LowByteOfIntOperand"}};
    return "{IrEffectCountKind::" + kKinds.at(count.kind) + ", " + std::to_string(count.value) + "}";
}

void emitIrCmdEffects(std::ostream& os, const std::vector<IrCmdDef>& cmds)
{
    CodeWriter out(os);
    out.raw(kHeaderBanner);
    out.raw("// Per-command effects, from the vm-effects, location-tracking, dead-store and heap-effects clauses in Luna/defs/ir:\n"
            "// read by visitVmRegDefsUses, IrValueLocationTracking and dead-store elimination\n"
            "#pragma once\n\n"
            "#include \"Luau/IrData.h\"\n\n"
            "#include <stdint.h>\n\n");
    openNamespaces(out);
    out.line();

    size_t maxVmEffects = 1;
    for (const auto& cmd : cmds)
        maxVmEffects = std::max(maxVmEffects, cmd.vmEffects.size());

    std::vector<std::string> vmHooks, locationHooks, deadStoreHooks;
    for (const auto& cmd : cmds)
    {
        auto add = [](std::vector<std::string>& to, const std::string& hook) {
            if (!hook.empty() && std::find(to.begin(), to.end(), hook) == to.end())
                to.push_back(hook);
        };
        add(vmHooks, cmd.vmHook);
        add(locationHooks, cmd.locationBeforeHook);
        add(locationHooks, cmd.locationAfterHook);
        add(deadStoreHooks, cmd.deadStoreHook);
    }

    auto emitEnum = [&](const std::string& name, const std::string& comment, const std::vector<std::string>& values) {
        out.line("// " + comment);
        out.line("enum class " + name + " : uint8_t");
        out.line("{");
        out.indent();
        for (const auto& value : values)
            out.line(value + ",");
        out.dedent();
        out.line("};");
        out.line();
    };

    emitEnum("IrVmEffectKind", "A VM register use or def (vm-effects)", {"Use", "MaybeUse", "UseRange", "UseVarargs", "Def", "MaybeDef", "DefRange"});
    emitEnum("IrEffectCountKind", "A register count: a literal (-1 is up to the stack top) or a constant operand", {"None", "Literal", "IntOperand", "UintOperand", "LowByteOfIntOperand"});
    emitEnum("IrLocationEffectKind", "A value location effect (location-tracking)", {"None", "Invalidate", "InvalidateKeepValues", "InvalidateRange", "RestoreFromLoad", "RestoreFromStore"});
    emitEnum("IrDeadStoreKind", "How dead-store elimination treats a command (dead-store)", {"Visit", "None", "LiveIns", "LiveInsNoExitSync", "LiveOuts", "Allocation", "Hook"});

    auto hookEnum = [&](const std::string& name, const std::string& comment, const std::vector<std::string>& hooks) {
        std::vector<std::string> values = {"None"};
        for (const auto& hook : hooks)
            values.push_back(pascalCase(hook));
        emitEnum(name, comment, values);
    };
    hookEnum("IrVmEffectsHook", "Hand-written vm-effects (IrVisitUseDef.h); runs after the declared uses and before the declared defs", vmHooks);
    hookEnum("IrLocationHook", "Hand-written location-tracking (IrValueLocationTracking.cpp)", locationHooks);
    hookEnum("IrDeadStoreHook", "Hand-written dead-store handling (OptimizeDeadStore.cpp)", deadStoreHooks);

    out.block("struct IrEffectCount", [&]() {
        out.line("IrEffectCountKind kind = IrEffectCountKind::None;");
        out.line("int16_t value = 0; // the literal, or the operand index");
    });
    out.raw(";\n\n");
    out.block("struct IrVmEffect", [&]() {
        out.line("IrVmEffectKind kind = IrVmEffectKind::Use;");
        out.line("uint8_t op = 0;");
        out.line("uint8_t offset = 0; // added to the operand's register");
        out.line("IrEffectCount count; // UseRange/DefRange");
    });
    out.raw(";\n\n");
    out.block("struct IrLocationEffect", [&]() {
        out.line("IrLocationEffectKind kind = IrLocationEffectKind::None;");
        out.line("uint8_t op = 0;");
        out.line("uint8_t offset = 0;");
        out.line("uint8_t valueOp = 0; // RestoreFromStore");
        out.line("IrEffectCount count; // InvalidateRange");
    });
    out.raw(";\n\n");

    out.line("inline constexpr int kMaxIrVmEffects = " + std::to_string(maxVmEffects) + ";");
    out.line();
    out.block("struct IrCmdEffects", [&]() {
        out.line("// vm-effects; without them the command has no VM register operands");
        out.line("bool declaresVmRegs = false;");
        out.line("uint8_t vmEffectCount = 0;");
        out.line("IrVmEffect vmEffects[kMaxIrVmEffects] = {}; // uses first, then defs");
        out.line("IrVmEffectsHook vmHook = IrVmEffectsHook::None;");
        out.line();
        out.line("// location-tracking; without it the command has no VM register operands");
        out.line("bool declaresLocations = false;");
        out.line("IrLocationEffect locationBefore;");
        out.line("IrLocationEffect locationAfter;");
        out.line("IrLocationHook locationBeforeHook = IrLocationHook::None;");
        out.line("IrLocationHook locationAfterHook = IrLocationHook::None;");
        out.line();
        out.line("// dead-store");
        out.line("IrDeadStoreKind deadStore = IrDeadStoreKind::Visit;");
        out.line("uint8_t deadStoreTarget = 0; // LiveIns/LiveInsNoExitSync: the target operand");
        out.line("IrDeadStoreHook deadStoreHook = IrDeadStoreHook::None;");
        out.line("int8_t allocationWriteOp = -1; // writes-allocation: the pointer operand");
        out.line("int8_t storeHintDest = -1;     // store-hint");
        out.line("int8_t storeHintValue = -1;");
        out.line("IrValueKind storeHintKind = IrValueKind::Unknown; // Unknown: the value's own kind");
        out.line();
        out.line("// heap-effects");
        out.line("bool mayGc = false;");
        out.line("bool reentersVm = false;");
        out.line();
        out.line("// Builders for the table below: each sets one thing and returns the result");
        auto builder = [&](const std::string& signature, const std::vector<std::string>& body) {
            out.block("constexpr IrCmdEffects " + signature + " const", [&]() {
                out.line("IrCmdEffects e = *this;");
                for (const auto& line : body)
                    out.line(line);
                out.line("return e;");
            });
        };
        builder("vm(IrVmEffectKind kind, uint8_t op, uint8_t offset = 0, IrEffectCount count = {})",
            {"e.declaresVmRegs = true;", "e.vmEffects[e.vmEffectCount++] = {kind, op, offset, count};"});
        builder("vmNone()", {"e.declaresVmRegs = true;"});
        builder("vmHookIs(IrVmEffectsHook hook)", {"e.declaresVmRegs = true;", "e.vmHook = hook;"});
        builder("locationsNone()", {"e.declaresLocations = true;"});
        builder("before(IrLocationEffect effect)", {"e.declaresLocations = true;", "e.locationBefore = effect;"});
        builder("after(IrLocationEffect effect)", {"e.declaresLocations = true;", "e.locationAfter = effect;"});
        builder("beforeHook(IrLocationHook hook)", {"e.declaresLocations = true;", "e.locationBeforeHook = hook;"});
        builder("afterHook(IrLocationHook hook)", {"e.declaresLocations = true;", "e.locationAfterHook = hook;"});
        builder("deadStoreIs(IrDeadStoreKind kind, uint8_t target = 0)", {"e.deadStore = kind;", "e.deadStoreTarget = target;"});
        builder("deadStoreHookIs(IrDeadStoreHook hook)", {"e.deadStore = IrDeadStoreKind::Hook;", "e.deadStoreHook = hook;"});
        builder("writesAllocation(int8_t op)", {"e.allocationWriteOp = op;"});
        builder("storeHint(int8_t dest, int8_t value, IrValueKind kind)", {"e.storeHintDest = dest;", "e.storeHintValue = value;", "e.storeHintKind = kind;"});
        builder("mayGcIs()", {"e.mayGc = true;"});
        builder("reentersVmIs()", {"e.reentersVm = true;"});
    });
    out.raw(";\n\n");

    out.line("inline constexpr IrCmdEffects kIrCmdEffects[] = {");
    out.indent();
    for (const auto& cmd : cmds)
    {
        static const std::map<std::string, std::string> kVmKinds = {{"use", "Use"}, {"maybe-use", "MaybeUse"}, {"use-range", "UseRange"},
            {"use-varargs", "UseVarargs"}, {"def", "Def"}, {"maybe-def", "MaybeDef"}, {"def-range", "DefRange"}};
        static const std::map<std::string, std::string> kLocationKinds = {{"invalidate", "Invalidate"}, {"invalidate-keep-values", "InvalidateKeepValues"},
            {"invalidate-range", "InvalidateRange"}, {"restore-from-load", "RestoreFromLoad"}, {"restore-from-store", "RestoreFromStore"}};
        static const std::map<std::string, std::string> kDeadStoreKinds = {{"visit", "Visit"}, {"none", "None"}, {"live-ins", "LiveIns"},
            {"live-ins-no-exit-sync", "LiveInsNoExitSync"}, {"live-outs", "LiveOuts"}, {"allocation", "Allocation"}, {"hook", "Hook"}};

        auto location = [&](const IrLocationEffectDef& e) {
            return "{IrLocationEffectKind::" + kLocationKinds.at(e.kind) + ", " + std::to_string(e.op) + ", " + std::to_string(e.offset) + ", " +
                   std::to_string(e.valueOp) + ", " + countInit(e.count) + "}";
        };

        std::string entry = "IrCmdEffects{}";
        for (const auto& e : cmd.vmEffects)
        {
            entry += ".vm(IrVmEffectKind::" + kVmKinds.at(e.kind) + ", " + std::to_string(e.op);
            if (e.offset || e.count.kind != "none")
                entry += ", " + std::to_string(e.offset);
            if (e.count.kind != "none")
                entry += ", " + countInit(e.count);
            entry += ")";
        }
        if (!cmd.vmHook.empty())
            entry += ".vmHookIs(IrVmEffectsHook::" + pascalCase(cmd.vmHook) + ")";
        else if (cmd.hasVmEffects && cmd.vmEffects.empty())
            entry += ".vmNone()";

        for (const auto& e : cmd.locationBefore)
            entry += ".before(" + location(e) + ")";
        for (const auto& e : cmd.locationAfter)
            entry += ".after(" + location(e) + ")";
        if (!cmd.locationBeforeHook.empty())
            entry += ".beforeHook(IrLocationHook::" + pascalCase(cmd.locationBeforeHook) + ")";
        if (!cmd.locationAfterHook.empty())
            entry += ".afterHook(IrLocationHook::" + pascalCase(cmd.locationAfterHook) + ")";
        if (cmd.hasLocationTracking && cmd.locationBefore.empty() && cmd.locationAfter.empty() && cmd.locationBeforeHook.empty() && cmd.locationAfterHook.empty())
            entry += ".locationsNone()";

        if (cmd.deadStore == "hook")
            entry += ".deadStoreHookIs(IrDeadStoreHook::" + pascalCase(cmd.deadStoreHook) + ")";
        else if (cmd.deadStore != "visit")
            entry += ".deadStoreIs(IrDeadStoreKind::" + kDeadStoreKinds.at(cmd.deadStore) + (cmd.deadStoreTarget >= 0 ? ", " + std::to_string(cmd.deadStoreTarget) : "") + ")";
        if (cmd.allocationWriteOp >= 0)
            entry += ".writesAllocation(" + std::to_string(cmd.allocationWriteOp) + ")";
        if (cmd.storeHintDest >= 0)
            entry += ".storeHint(" + std::to_string(cmd.storeHintDest) + ", " + std::to_string(cmd.storeHintValue) + ", IrValueKind::" + cmd.storeHintKind + ")";
        if (cmd.heapEffects.count("may-gc"))
            entry += ".mayGcIs()";
        if (cmd.heapEffects.count("reenters-vm"))
            entry += ".reentersVmIs()";

        out.line("// " + cmd.name);
        out.line(entry + ",");
    }
    out.dedent();
    out.line("};");
    out.line("static_assert(sizeof(kIrCmdEffects) / sizeof(kIrCmdEffects[0]) == " + std::to_string(cmds.size()) + ", \"one entry per IrCmd\");");
    out.line();
    out.block("inline const IrCmdEffects& getCmdEffects(IrCmd cmd)", [&]() {
        out.line("return kIrCmdEffects[unsigned(cmd)];");
    });
    out.line();
    closeNamespaces(out);
}

static std::string docLine(const std::string& text)
{
    return text.empty() ? "//" : "// " + text;
}

void emitIrCmdEnum(std::ostream& os, const std::vector<IrCmdDef>& cmds)
{
    CodeWriter out(os);
    out.raw(kHeaderBanner);
    out.raw("// The IrCmd enum, from the define-ircmd declarations in Luna/defs/ir (included by Luau/IrData.h)\n"
            "#pragma once\n\n"
            "#include <stdint.h>\n\n");
    openNamespaces(out);
    out.line();
    out.line("enum class IrCmd : uint8_t");
    out.line("{");
    out.indent();

    // Consecutive commands with the same docs share one comment block, like in a hand-written enum
    for (size_t i = 0; i < cmds.size(); ++i)
    {
        bool continuesBlock = i > 0 && !cmds[i].docs.empty() && cmds[i].docs == cmds[i - 1].docs;
        if (!continuesBlock)
        {
            if (i > 0)
                out.line();
            for (const auto& doc : cmds[i].docs)
                out.line(docLine(doc));
        }
        out.line(cmds[i].name + ",");
    }

    out.dedent();
    out.line("};");
    out.line();
    closeNamespaces(out);
}

