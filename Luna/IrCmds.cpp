static const std::set<std::string> kClasses = {"value", "effect", "guard", "terminator", "pseudo"};

// deprecated/ flags reproduce today's hand-written heuristics until side effects are derived from declared effects
static const std::set<std::string> kFlags = {"deprecated/has-side-effects", "deprecated/is-unsafe-to-sink", "dirty-high-bits"};

static const std::set<std::string> kHeapEffects = {"invalidates-safe-env"};

// Fast flags that can make extra operand kinds legal (flag-specific); the verifier checks each of them
static const std::vector<std::string> kOperandFlags = {"DebugLuauAbortingChecks"};

// What an operand kind matches: IrOpKinds, plus the IrValueKinds of Inst operands and IrConstKinds of Constant ones
struct OperandKindInfo
{
    std::vector<std::string> opKinds;
    std::vector<std::string> valueKinds;
    std::vector<std::string> constKinds;
};

static const std::map<std::string, OperandKindInfo> kOperandKinds = [] {
    std::map<std::string, OperandKindInfo> kinds = {
        // An instruction result or a constant of the same kind (float constants are Double constants)
        {"int", {{"Inst", "Constant"}, {"Int"}, {"Int"}}},
        {"int64", {{"Inst", "Constant"}, {"Int64"}, {"Int64"}}},
        {"double", {{"Inst", "Constant"}, {"Double"}, {"Double"}}},
        {"float", {{"Inst", "Constant"}, {"Float"}, {"Double"}}},
        {"tag", {{"Inst", "Constant"}, {"Tag"}, {"Tag"}}},
        {"pointer", {{"Inst"}, {"Pointer"}, {}}},
        {"tvalue", {{"Inst"}, {"Tvalue"}, {}}},

        {"const-int", {{"Constant"}, {}, {"Int"}}},
        {"const-uint", {{"Constant"}, {}, {"Uint"}}},
        {"const-int64", {{"Constant"}, {}, {"Int64"}}},
        {"const-double", {{"Constant"}, {}, {"Double"}}},
        {"const-tag", {{"Constant"}, {}, {"Tag"}}},
        {"import", {{"Constant"}, {}, {"Import"}}},

        {"Rn", {{"VmReg"}, {}, {}}},
        {"Kn", {{"VmConst"}, {}, {}}},
        {"UPn", {{"VmUpvalue"}, {}, {}}},
        {"block", {{"Block"}, {}, {}}},
        {"vmexit", {{"VmExit"}, {}, {}}},
        {"undef", {{"Undef"}, {}, {}}},
        {"cond", {{"Condition"}, {}, {}}},
        {"none", {{"None"}, {}, {}}},
        {"any", {{"Undef", "Constant", "Condition", "Inst", "Block", "VmReg", "VmConst", "VmUpvalue", "VmExit"},
                    {"Tag", "Int", "Int64", "Pointer", "Float", "Double", "Tvalue"}, {"Int", "Int64", "Uint", "Double", "Tag", "Import"}}},
    };
    // Only an instruction result of that kind
    for (const char* kind : {"int", "int64", "double", "float", "tag", "pointer", "tvalue"})
        kinds[std::string("inst-") + kind] = {{"Inst"}, kinds[kind].valueKinds, {}};
    return kinds;
}();

static std::string knownOperandKinds()
{
    std::string list;
    for (const auto& [name, info] : kOperandKinds)
        list += (list.empty() ? ":" : " :") + name;
    return list;
}

// [name :kind|:kind...]
static IrOperandDef parseOperand(const SExpr& op, const std::string& cmdName)
{
    if (op.kind != SExprKind::BracketList || op.elements.size() != 2 || !op.elements[0].isSymbol() || !op.elements[1].isKeyword())
        throw CompileError(op, "Operand must be [name :kind] or [name :kind|:kind...] in " + cmdName);

    IrOperandDef def;
    def.name = op.elements[0].text;
    def.loc = op.loc;

    const std::string& text = op.elements[1].text;
    size_t start = 0;
    while (start <= text.size())
    {
        size_t end = text.find('|', start);
        std::string part = text.substr(start, end == std::string::npos ? std::string::npos : end - start);
        if (part.size() < 2 || part[0] != ':' || !kOperandKinds.count(part.substr(1)))
            throw CompileError(op.elements[1], "Unknown operand kind '" + part + "' (expected " + knownOperandKinds() + ", joined with |)");
        if (std::find(def.kinds.begin(), def.kinds.end(), part.substr(1)) != def.kinds.end())
            throw CompileError(op.elements[1], "Duplicate operand kind " + part);
        def.kinds.push_back(part.substr(1));
        if (end == std::string::npos)
            break;
        start = end + 1;
    }
    return def;
}

static bool allowsKind(const IrOperandDef& op, const std::string& kind)
{
    return std::find(op.kinds.begin(), op.kinds.end(), kind) != op.kinds.end();
}

static std::string keywordName(const SExpr& expr)
{
    return expr.text.substr(1);
}

static bool isCommandName(const std::string& name)
{
    if (name.empty() || !std::isupper(static_cast<unsigned char>(name[0])))
        return false;
    for (char c : name)
    {
        if (!std::isupper(static_cast<unsigned char>(c)) && !std::isdigit(static_cast<unsigned char>(c)) && c != '_')
            return false;
    }
    return true;
}

// Docs on define-ircmd only go on the form itself (for now): a trailing doc on the header line moves to the form,
// like for define-rule; anywhere else inside the form is an error
static void checkClauseDocs(SExpr& expr, SExpr& form)
{
    if (expr.trailingDoc && expr.docs.empty() && expr.endLine == form.loc.line && !form.trailingDoc)
    {
        form.trailingDoc = std::move(expr.trailingDoc);
        expr.trailingDoc.reset();
    }
    if (expr.hasDocs())
        throw CompileError(expr, "Doc comments (~) inside define-ircmd aren't supported yet; put them before the form");
    for (auto& el : expr.elements)
        checkClauseDocs(el, form);
}

static IrCmdDef parseIrCmd(const SExpr& original)
{
    SExpr form = original;
    if (form.elements.size() < 2 || !form.elements[1].isSymbol() || !isCommandName(form.elements[1].text))
        throw CompileError(form, "define-ircmd needs an UPPER_SNAKE command name: (define-ircmd NAME <clause>...)");

    for (size_t i = 1; i < form.elements.size(); ++i)
        checkClauseDocs(form.elements[i], form);

    IrCmdDef cmd;
    cmd.name = form.elements[1].text;
    cmd.loc = form.elements[1].loc;
    cmd.docs = form.docs;
    if (form.trailingDoc)
        cmd.docs.push_back(*form.trailingDoc);

    std::set<std::string> seenClauses;
    for (size_t i = 2; i < form.elements.size(); ++i)
    {
        const SExpr& clause = form.elements[i];
        if (!clause.isList() || clause.elements.empty() || !clause.elements[0].isSymbol())
            throw CompileError(clause, "define-ircmd clause must be a list like (result :int)");

        const std::string& kind = clause.elements[0].text;
        if (!seenClauses.insert(kind).second)
            throw CompileError(clause, "Duplicate " + kind + " clause in define-ircmd " + cmd.name);

        auto keywordArgs = [&](const std::set<std::string>& allowed, const char* what) {
            std::set<std::string> result;
            for (size_t j = 1; j < clause.elements.size(); ++j)
            {
                const SExpr& arg = clause.elements[j];
                if (!arg.isKeyword() || !allowed.count(keywordName(arg)))
                {
                    std::string list;
                    for (const auto& a : allowed)
                        list += (list.empty() ? ":" : ", :") + a;
                    throw CompileError(arg, std::string("Unknown ") + what + " '" + arg.text + "' (expected one of " + list + ")");
                }
                if (!result.insert(keywordName(arg)).second)
                    throw CompileError(arg, std::string("Duplicate ") + what + " " + arg.text);
            }
            return result;
        };

        if (kind == "operands")
        {
            std::set<std::string> names;
            for (size_t j = 1; j < clause.elements.size(); ++j)
            {
                IrOperandDef op = parseOperand(clause.elements[j], cmd.name);
                if (!names.insert(op.name).second)
                    throw CompileError(clause.elements[j], "Duplicate operand '" + op.name + "' in " + cmd.name);

                // Optional operands are trailing: once one can be absent, all later ones can be too
                if (!cmd.operands.empty() && allowsKind(cmd.operands.back(), "none") && !allowsKind(op, "none"))
                    throw CompileError(clause.elements[j], "Operand '" + op.name + "' follows optional operand '" + cmd.operands.back().name +
                        "', so it has to allow :none as well");
                cmd.operands.push_back(std::move(op));
            }
            if (cmd.operands.size() > kMaxOperands)
                throw CompileError(clause, cmd.name + " has " + std::to_string(cmd.operands.size()) + " operands; IR instructions have at most 7 (A..G)");
        }
        else if (kind == "target-specific" || kind == "flag-specific")
        {
            // [:key [operand :kinds]...] groups; operands are resolved after all clauses are read
            bool byTarget = kind == "target-specific";
            const std::vector<std::string>& keys = byTarget ? knownTargets() : kOperandFlags;
            std::vector<IrOperandExtras>& groups = byTarget ? cmd.targetSpecific : cmd.flagSpecific;

            for (size_t j = 1; j < clause.elements.size(); ++j)
            {
                const SExpr& group = clause.elements[j];
                if (group.kind != SExprKind::BracketList || group.elements.empty() || !group.elements[0].isKeyword())
                    throw CompileError(group, kind + " groups look like [" + (byTarget ? ":x64" : ":DebugLuauAbortingChecks") + " [operand :kind]...]");

                std::string key = keywordName(group.elements[0]);
                if (std::find(keys.begin(), keys.end(), key) == keys.end())
                {
                    std::string list;
                    for (const auto& k : keys)
                        list += (list.empty() ? ":" : ", :") + k;
                    throw CompileError(group.elements[0], std::string("Unknown ") + (byTarget ? "target" : "flag") + " " + group.elements[0].text + " (expected " + list + ")");
                }
                if (std::any_of(groups.begin(), groups.end(), [&](const IrOperandExtras& g) { return g.key == key; }))
                    throw CompileError(group.elements[0], "Duplicate " + kind + " group for " + group.elements[0].text);
                if (group.elements.size() < 2)
                    throw CompileError(group, "The " + group.elements[0].text + " group needs at least one [operand :kind]");

                IrOperandExtras extras;
                extras.key = key;
                extras.loc = group.loc;
                for (size_t k = 1; k < group.elements.size(); ++k)
                    extras.operands.push_back(parseOperand(group.elements[k], cmd.name));
                groups.push_back(std::move(extras));
            }
            if (groups.empty())
                throw CompileError(clause, kind + " needs at least one [" + (byTarget ? ":x64" : ":DebugLuauAbortingChecks") + " [operand :kind]...] group");
        }
        else if (kind == "result")
        {
            if (clause.elements.size() != 2 || !clause.elements[1].isKeyword() || !kResultKinds.count(keywordName(clause.elements[1])))
                throw CompileError(clause, "result expects one of :tag, :int, :int64, :pointer, :float, :double, :tvalue, :unknown");
            cmd.result = kResultKinds.at(keywordName(clause.elements[1]));
        }
        else if (kind == "class")
        {
            if (clause.elements.size() != 2 || !clause.elements[1].isKeyword() || !kClasses.count(keywordName(clause.elements[1])))
                throw CompileError(clause, "class expects one of :value, :effect, :guard, :terminator, :pseudo");
            cmd.cls = keywordName(clause.elements[1]);
        }
        else if (kind == "flags")
        {
            cmd.flags = keywordArgs(kFlags, "flag");
        }
        else if (kind == "heap-effects")
        {
            cmd.heapEffects = keywordArgs(kHeapEffects, "heap effect");
        }
        else if (kind == "lowering")
        {
            if (clause.elements.size() != 2)
                throw CompileError(clause, "lowering expects a single rule call: (lowering (<rule> <args>...))");
            const SExpr& call = clause.elements[1];
            if (call.isKeyword(":semantics"))
                throw CompileError(call, "(lowering :semantics) isn't supported yet; name a define-rule");
            if (!call.isList() || call.kind != SExprKind::List || call.elements.empty() || !call.elements[0].isSymbol())
                throw CompileError(call, "lowering expects a rule call: (lowering (<rule> <args>...))");

            IrCmdLowering lowering;
            lowering.rule = call.elements[0].text;
            lowering.args.assign(call.elements.begin() + 1, call.elements.end());
            lowering.loc = call.loc;
            cmd.lowering = std::move(lowering);
        }
        else
        {
            throw CompileError(clause.elements[0], "Unknown define-ircmd clause '" + kind + "' (expected operands, target-specific, flag-specific, result, class, flags, heap-effects or lowering)");
        }
    }

    for (const auto* groups : {&cmd.targetSpecific, &cmd.flagSpecific})
    {
        for (const auto& group : *groups)
        {
            std::set<std::string> seen;
            for (const auto& extra : group.operands)
            {
                if (std::none_of(cmd.operands.begin(), cmd.operands.end(), [&](const IrOperandDef& op) { return op.name == extra.name; }))
                    throw CompileError(extra.loc, "'" + extra.name + "' isn't an operand of " + cmd.name);
                if (!seen.insert(extra.name).second)
                    throw CompileError(extra.loc, "Duplicate extra kinds for '" + extra.name + "' in the :" + group.key + " group");
            }
        }
    }

    if (cmd.cls.empty())
        throw CompileError(form, cmd.name + " needs a (class ...) clause");
    if (cmd.cls == "value" && cmd.result.empty())
        throw CompileError(form, cmd.name + " is a :value command but has no (result ...)");
    if (cmd.cls == "effect" && !cmd.result.empty())
        throw CompileError(form, cmd.name + " is an :effect command but has a result; use :value");
    if (cmd.cls == "pseudo" && cmd.lowering)
        throw CompileError(cmd.lowering->loc, cmd.name + " is a pseudo-instruction and isn't lowered");
    if (cmd.cls != "pseudo" && !cmd.lowering)
        throw CompileError(form, cmd.name + " needs a (lowering (<rule> <args>...)) clause");

    return cmd;
}

std::vector<IrCmdDef> parseIrCmds(const std::vector<SExpr>& program)
{
    std::vector<IrCmdDef> cmds;
    std::unordered_map<std::string, SourceLocation> seen;

    for (const auto& form : program)
    {
        if (!form.isList("define-ircmd"))
            continue;

        IrCmdDef cmd = parseIrCmd(form);
        auto [prev, inserted] = seen.emplace(cmd.name, cmd.loc);
        if (!inserted)
            throw CompileError(cmd.loc, "Duplicate define-ircmd " + cmd.name + " (previously defined at " + prev->second.toString() + ")");

        // A value-initialized IrInst is command 0, which should be the no-op
        if (cmd.name == "NOP" && !cmds.empty())
            throw CompileError(cmd.loc, "NOP must be the first define-ircmd, so a zero-initialized instruction is a no-op");

        cmds.push_back(std::move(cmd));
    }

    if (cmds.size() > kMaxCommands)
        throw CompileError(cmds[kMaxCommands].loc, "More than 256 IR commands; IrCmd is a uint8_t");

    return cmds;
}

// The operand kinds a rule parameter can read: e.g. an :int parameter reads with intOp, which only handles constants
static const std::map<std::string, std::set<std::string>> kParamKinds = [] {
    std::set<std::string> instKinds;
    for (const auto& [name, info] : kOperandKinds)
    {
        if (name.rfind("inst-", 0) == 0)
            instKinds.insert(name);
    }
    return std::map<std::string, std::set<std::string>>{
        {"int", {"const-int"}},
        {"uint", {"const-uint"}},
        {"tag", {"const-tag"}},
        {"cond", {"cond"}},
        {"upvalue", {"UPn"}},
        {"reg", instKinds},
        {"label", {"block", "vmexit", "undef"}},
    };
}();

static void checkParamKinds(const IrCmdDef& cmd, const IrOperandDef& op, const RuleParam& param, const SExpr& arg)
{
    auto allowed = kParamKinds.find(param.type);
    if (allowed == kParamKinds.end())
        return; // :op parameters handle whatever they get

    auto check = [&](const IrOperandDef& def, const std::string& where) {
        for (const auto& kind : def.kinds)
        {
            // An absent optional operand is never read unless the rule checks it's there
            if (kind != "none" && !allowed->second.count(kind))
            {
                throw CompileError(arg, cmd.name + " operand '" + op.name + "' can be :" + kind + where + ", but rule parameter '" + param.name +
                    "' is :" + param.type + ", which can't read that; use an :op parameter or narrow the operand's kinds");
            }
        }
    };
    check(op, "");
    for (const auto& group : cmd.targetSpecific)
        for (const auto& extra : group.operands)
            if (extra.name == op.name)
                check(extra, " (on " + group.key + ")");
    for (const auto& group : cmd.flagSpecific)
        for (const auto& extra : group.operands)
            if (extra.name == op.name)
                check(extra, " (with " + group.key + ")");
}

std::vector<LoweringInstance> linkLowerings(const std::vector<IrCmdDef>& cmds, const std::vector<Rule>& rules)
{
    std::unordered_map<std::string, size_t> ruleIndex;
    for (size_t i = 0; i < rules.size(); ++i)
        ruleIndex[rules[i].name] = i;

    std::vector<std::vector<LoweringInstance>> byRule(rules.size());

    for (const auto& cmd : cmds)
    {
        if (!cmd.lowering)
            continue;

        const IrCmdLowering& lowering = *cmd.lowering;
        auto it = ruleIndex.find(lowering.rule);
        if (it == ruleIndex.end())
            throw CompileError(lowering.loc, cmd.name + " is lowered by '" + lowering.rule + "', which isn't a define-rule");

        const Rule& rule = rules[it->second];
        if (lowering.args.size() != rule.params.size())
        {
            throw CompileError(lowering.loc, "Rule " + rule.name + " takes " + std::to_string(rule.params.size()) + " argument(s), but " + cmd.name +
                " passes " + std::to_string(lowering.args.size()) + " (rule defined at " + rule.loc.toString() + ")");
        }

        LoweringInstance instance;
        instance.cmdName = cmd.name;
        instance.rule = &rule;
        for (size_t i = 0; i < lowering.args.size(); ++i)
        {
            const SExpr& arg = lowering.args[i];
            if (arg.isSymbol())
            {
                auto op = std::find_if(cmd.operands.begin(), cmd.operands.end(), [&](const IrOperandDef& o) { return o.name == arg.text; });
                if (op == cmd.operands.end())
                {
                    std::string list;
                    for (const auto& o : cmd.operands)
                        list += (list.empty() ? "" : ", ") + o.name;
                    throw CompileError(arg, "'" + arg.text + "' isn't an operand of " + cmd.name + " (operands: " + (list.empty() ? "none" : list) + ")");
                }
                checkParamKinds(cmd, *op, rule.params[i], arg);
                instance.operandIndex.push_back(int(op - cmd.operands.begin()));
                instance.literals.emplace_back();
            }
            else if (arg.isNumber() || arg.isKeyword())
            {
                instance.operandIndex.push_back(-1);
                instance.literals.push_back(arg);
            }
            else
            {
                throw CompileError(arg, "Lowering arguments must be operand names or number/keyword literals");
            }
        }

        byRule[it->second].push_back(std::move(instance));
    }

    // Rule order (then command order) keeps the generated lowering functions in the order of the rules
    std::vector<LoweringInstance> instances;
    for (size_t i = 0; i < rules.size(); ++i)
    {
        if (byRule[i].empty())
            throw CompileError(rules[i].loc, "define-rule " + rules[i].name + " isn't used by any define-ircmd (add a (lowering (" + rules[i].name + " ...)) clause)");
        for (auto& instance : byRule[i])
            instances.push_back(std::move(instance));
    }
    return instances;
}

std::vector<DispatchEntry> loweringDispatch(const std::vector<IrCmdDef>& cmds)
{
    std::vector<DispatchEntry> dispatch;
    for (const auto& cmd : cmds)
        dispatch.push_back({cmd.name, cmd.cls != "pseudo"});
    return dispatch;
}

static bool hasSideEffects(const IrCmdDef& cmd)
{
    // Today's heuristic: an instruction without a result must be there for its side effects
    if (cmd.cls == "pseudo")
        return false;
    if (cmd.flags.count("deprecated/has-side-effects"))
        return true;
    return cmd.result.empty();
}

static void openNamespaces(CodeWriter& out)
{
    out.line("namespace Luau");
    out.line("{");
    out.line("namespace CodeGen");
    out.line("{");
}

